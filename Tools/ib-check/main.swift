// RunwayIBCheck: loads Interface Builder documents (.xib, .storyboard)
// headlessly, without their app's code, and reports what Runway's AppKit
// makes of them.
//
//   swift run RunwayIBCheck <file or directory>… [--markdown report.md]
//   swift run RunwayIBCheck --show <file>     (opens its windows, or its first
//                                             view or controller in a window)
//
// Directories are searched for macOS documents (iOS ones are skipped).

import AppKit
import Foundation
import RunwayCore

@MainActor
func main() {
    var args = Array(CommandLine.arguments.dropFirst())
    var markdown: String?
    var root: String?
    if let i = args.firstIndex(of: "--markdown"), i + 1 < args.count { markdown = args[i + 1]; args.removeSubrange(i...(i + 1)) }
    if let i = args.firstIndex(of: "--root"), i + 1 < args.count { root = args[i + 1]; args.removeSubrange(i...(i + 1)) }
    if let i = args.firstIndex(of: "--show"), i + 1 < args.count {
        let delegate = ShowDelegate(URL(fileURLWithPath: args[i + 1]))
        NSApplication.shared.delegate = delegate
        NSApplication.shared.run()
        _ = delegate
        return
    }
    Runway.install(HeadlessBackend())
    var files: [URL] = []
    let fm = FileManager.default
    for a in args {
        var isDir: ObjCBool = false
        guard fm.fileExists(atPath: a, isDirectory: &isDir) else { continue }
        if isDir.boolValue {
            let e = fm.enumerator(atPath: a)
            while let rel = e?.nextObject() as? String {
                guard rel.hasSuffix(".xib") || rel.hasSuffix(".storyboard") else { continue }
                let u = URL(fileURLWithPath: a).appendingPathComponent(rel)
                guard let head = try? String(contentsOf: u, encoding: .utf8).prefix(600), head.contains("MacOSX") else { continue }
                files.append(u)
            }
        } else { files.append(URL(fileURLWithPath: a)) }
    }
    files.sort { $0.path < $1.path }
    var results: [IBCheckResult] = []
    for f in files {
        let r = IBCheck.check(f)
        results.append(r)
        let name = root.map { f.path.replacingOccurrences(of: $0.hasSuffix("/") ? $0 : $0 + "/", with: "") } ?? f.path
        if let e = r.error { print("\(name): ERROR \(e)"); continue }
        print("\(name): \(r.objects) objects (\(r.views) views), \(r.constraints) constraints, \(r.connections) connections, "
              + "\(r.customClasses.count) app classes, \(r.unsupportedElements.values.reduce(0, +)) unread elements, "
              + "\(r.unsupportedAttributes.values.reduce(0, +)) unread attributes")
    }
    if let markdown { writeReport(results, to: markdown, root: root) }
}

@MainActor
func writeReport(_ results: [IBCheckResult], to path: String, root: String?) {
    func rel(_ p: String) -> String { root.map { p.replacingOccurrences(of: $0.hasSuffix("/") ? $0 : $0 + "/", with: "") } ?? p }
    var md = "# Interface Builder documents in the corpus\n\n"
    md += "Generated by `swift run RunwayIBCheck <corpus> --markdown Tools/corpus/ib-results.md` (Tools/ib-check): every macOS `.xib` and "
    md += "`.storyboard` loaded headlessly by Runway's AppKit **without the apps' code** — each xib with a stand-in File's Owner, each "
    md += "storyboard's Application scene plus every controller scene, with views and windows loaded. App classes (`customClass`) "
    md += "can't be found without the app (Runway uses the AppKit base class instead, as Cocoa would fail to), so outlets to "
    md += "them aren't set here; in a staged app the generated class table supplies them.\n\n"
    let ok = results.filter { $0.error == nil }
    let tot = (files: results.count, ok: ok.count, objects: ok.map(\.objects).reduce(0, +), views: ok.map(\.views).reduce(0, +),
               constraints: ok.map(\.constraints).reduce(0, +), connections: ok.map(\.connections).reduce(0, +),
               elements: ok.map(\.elements).reduce(0, +))
    md += "What \"not read\" means: the loader marks every attribute and child element it reads; anything left is listed at the end. "
    md += "Known gaps behind the remaining entries: attributed-string runs (`<attributedString>` fragments' fonts and colours: the text is "
    md += "used, its styling isn't — most of the `font.*`/`color.*` attributes), cell-based table data cells (`dataCell` where a column has "
    md += "no view prototype), `NSPathControl`, `WKWebView` (a plain view stands in: WebKit sits above AppKit), view shadows, input "
    md += "source locales of secure fields, and custom `NSCell` subclasses. Window positioning masks, popup button `behavior` and other "
    md += "Xcode bookkeeping are read and deliberately ignored.\n\n"
    md += "## Totals\n\n"
    md += "| Documents | Loaded | XML elements | Objects | Views | Constraints | Connections |\n|---|---|---|---|---|---|---|\n"
    md += "| \(tot.files) | \(tot.ok) | \(tot.elements) | \(tot.objects) | \(tot.views) | \(tot.constraints) | \(tot.connections) |\n\n"
    md += "## Per document\n\n"
    md += "| Document | Objects | Views | Constraints | Connections | App classes | Unread elements | Unread attributes |\n|---|---|---|---|---|---|---|---|\n"
    for r in results {
        if let e = r.error { md += "| \(rel(r.file)) | error: \(e) | | | | | | |\n"; continue }
        md += "| \(rel(r.file)) | \(r.objects) | \(r.views) | \(r.constraints) | \(r.connections) | \(r.customClasses.count) | "
        md += "\(r.unsupportedElements.values.reduce(0, +)) | \(r.unsupportedAttributes.values.reduce(0, +)) |\n"
    }
    var classes: [String: Int] = [:], elements: [String: Int] = [:], attributes: [String: Int] = [:]
    var custom = Set<String>()
    for r in ok {
        for (k, v) in r.classes { classes[k, default: 0] += v }
        for (k, v) in r.unsupportedElements { elements[k, default: 0] += v }
        for (k, v) in r.unsupportedAttributes { attributes[k, default: 0] += v }
        custom.formUnion(r.customClasses)
    }
    md += "\n## AppKit classes instantiated\n\n| Class | Count |\n|---|---|\n"
    for (k, v) in classes.sorted(by: { ($0.value, $1.key) > ($1.value, $0.key) }) { md += "| \(k) | \(v) |\n" }
    md += "\n## Elements not read (unsupported), by parent\n\n"
    md += elements.isEmpty ? "None.\n" : "| Element | Count |\n|---|---|\n"
    for (k, v) in elements.sorted(by: { ($0.value, $1.key) > ($1.value, $0.key) }) { md += "| `\(k)` | \(v) |\n" }
    md += "\n## Attributes not read (unsupported), by element\n\n"
    md += attributes.isEmpty ? "None.\n" : "| Attribute | Count |\n|---|---|\n"
    for (k, v) in attributes.sorted(by: { ($0.value, $1.key) > ($1.value, $0.key) }) { md += "| `\(k)` | \(v) |\n" }
    md += "\n## App classes named by the documents (\(custom.count))\n\n"
    md += custom.sorted().map { "`\($0)`" }.joined(separator: ", ") + "\n"
    try? md.write(toFile: path, atomically: true, encoding: .utf8)
    print("wrote \(path)")
}

final class ShowDelegate: NSObject, NSApplicationDelegate {
    let url: URL
    init(_ url: URL) { self.url = url }
    func applicationDidFinishLaunching(_ notification: Notification) { IBCheck.show(url) }
}

MainActor.assumeIsolated { main() }
