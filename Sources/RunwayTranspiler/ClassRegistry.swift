// The generated class table that lets AppKit find an app's classes by name
// (Interface Builder's `customClass`, NSClassFromString) and make them
// without an Objective-C runtime: see RunwayObjC's ClassRegistry.swift.
//
// The build tool writes one extra file into each staged target:
//
//     let text = RunwayTranspiler.classRegistrySource(module: "MyApp", files: [(path, source), …])
//     // → Sources/MyApp/_RunwayClassRegistry.swift (nil: nothing to register)
//
// The file declares `enum _RunwayClassRegistry: RunwayObjC.ClassRegistryProviding`,
// which RunwayObjC finds by its mangled name at run time; nothing calls it.
// Besides the classes by name it lists how to make the ones Swift can't
// make through a metatype: `init()` (custom objects in nibs, whose
// NSObject initializer isn't `required`) and NSWindow subclasses'
// `init(contentRect:styleMask:backing:defer:)`.

import Foundation
import SwiftParser
import SwiftSyntax

extension RunwayTranspiler {
    /// Swift source registering every class `files` declare (top-level and
    /// nested; not local, private or generic ones) under "Module.Name" and,
    /// for `@objc(Name)` classes, "Name". Nil when the files declare none.
    /// `aliases`: other module names documents may use for this module
    /// (an Xcode project's PRODUCT_MODULE_NAME when it differs from the
    /// SwiftPM target's), registered too.
    public static func classRegistrySource(module: String, aliases: [String] = [], files: [(path: String, source: String)]) -> String? {
        let trees = files.sorted(by: { $0.path < $1.path }).map { Parser.parse(source: $0.source) }
        // Extensions of generic types can't name their nested classes plainly.
        let generics = GenericTypes()
        for t in trees { generics.walk(t) }
        var found: [RegistryScanner.Found] = []
        for t in trees {
            let s = RegistryScanner(generic: generics.names)
            s.walk(t)
            found += s.classes
        }
        guard !found.isEmpty else { return nil }
        let bySimple = Dictionary(found.map { ($0.simpleName, $0) }, uniquingKeysWith: { a, _ in a })

        /// Whether `init()` (or the window initializer) reaches the class.
        func has(_ c: RegistryScanner.Found, _ wanted: [String], roots: Set<String>, depth: Int = 0) -> Bool {
            if depth > 20 { return false }
            if c.inits.contains(where: { $0.labels == wanted && !$0.isPrivate && !$0.failable }) { return true }
            // Inherits its superclass's initializers only when it declares
            // no designated ones.
            if c.inits.contains(where: { !$0.convenience }) { return false }
            guard let sup = c.superName else { return false }
            if let s = bySimple[sup] { return has(s, wanted, roots: roots, depth: depth + 1) }
            return roots.contains(sup)
        }
        let objectRoots: Set<String> = ["NSObject", "NSResponder", "NSWindowController", "NSViewController", "NSMenu", "NSMenuItem",
                                        "ValueTransformer", "NSValueTransformer", "Formatter", "NumberFormatter", "DateFormatter",
                                        "NSDocument", "NSDocumentController", "NSSplitViewController", "NSTabViewController"]
        let windowRoots: Set<String> = ["NSWindow", "NSPanel"]

        var classes = "", factories = "", windows = ""
        for c in found {
            for m in [module] + aliases.filter({ $0 != module }) {
                classes += Generate.wrap(c.conditions, "        c.append((\(literal(m + "." + c.qualifiedName)), \(c.qualifiedName).self))") + "\n"
            }
            if let o = c.objcName, o != c.qualifiedName {
                classes += Generate.wrap(c.conditions, "        c.append((\(literal(o)), \(c.qualifiedName).self))") + "\n"
            }
            if has(c, [], roots: objectRoots) {
                factories += Generate.wrap(c.conditions, "        f.append((\(c.qualifiedName).self, { \(c.qualifiedName)() }))") + "\n"
            }
            if has(c, ["contentRect", "styleMask", "backing", "defer"], roots: windowRoots) {
                windows += Generate.wrap(c.conditions, """
                        w.append((\(c.qualifiedName).self, { r, m in \(c.qualifiedName)(contentRect: r, styleMask: .init(rawValue: m), backing: .buffered, defer: true) }))
                """) + "\n"
            }
        }
        var out = """
        // Generated by RunwayTranspiler: this module's classes by name, for
        // Interface Builder documents and NSClassFromString.
        import RunwayObjC
        \(windows.isEmpty ? "" : "#if canImport(AppKit)\nimport AppKit\n#endif\n")
        enum _RunwayClassRegistry: RunwayObjC.ClassRegistryProviding {
            static var classes: [(String, AnyClass)] {
                var c: [(String, AnyClass)] = []
        \(classes)        return c
            }

        """
        if !factories.isEmpty {
            out += """
                static var factories: [(AnyClass, @MainActor @Sendable () -> AnyObject?)] {
                    var f: [(AnyClass, @MainActor @Sendable () -> AnyObject?)] = []
            \(factories)        return f
                }

            """
        }
        if !windows.isEmpty {
            out += """
                static var windowFactories: [(AnyClass, @MainActor @Sendable (CGRect, UInt) -> AnyObject)] {
                    var w: [(AnyClass, @MainActor @Sendable (CGRect, UInt) -> AnyObject)] = []
            \(windows)        return w
                }

            """
        }
        return out + "}\n"
    }

    /// The same for files on disk.
    public static func classRegistrySource(module: String, aliases: [String] = [], paths: [String]) -> String? {
        let files = paths.compactMap { p -> (path: String, source: String)? in
            guard let d = FileManager.default.contents(atPath: p), let s = String(data: d, encoding: .utf8) else { return nil }
            return (p, s)
        }
        return classRegistrySource(module: module, aliases: aliases, files: files)
    }

    private static func literal(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}

private final class RegistryScanner: SyntaxVisitor {
    struct Initializer { var labels: [String]; var convenience: Bool; var failable: Bool; var isPrivate: Bool }
    struct Found {
        var qualifiedName: String
        var simpleName: String
        var superName: String?
        var objcName: String?
        var conditions: [String]
        var inits: [Initializer] = []
    }
    var classes: [Found] = []
    /// Enclosing types: (name, usable from the generated file, index in `classes`).
    private var contexts: [(name: String, ok: Bool, index: Int?)] = []
    let generic: Set<String>

    init(generic: Set<String>) { self.generic = generic; super.init(viewMode: .sourceAccurate) }

    private func enter(_ name: String, generic: Bool, modifiers: DeclModifierListSyntax, index: Int? = nil) {
        let hidden = modifiers.contains { $0.name.text == "private" || $0.name.text == "fileprivate" }
        let ok = (contexts.last?.ok ?? true) && !generic && !hidden
        contexts.append(((contexts.last.map { $0.name + "." } ?? "") + name, ok, index))
    }

    override func visit(_ node: ClassDeclSyntax) -> SyntaxVisitorContinueKind {
        if isLocalDecl(node) { return .skipChildren }
        enter(node.name.text, generic: node.genericParameterClause != nil, modifiers: node.modifiers)
        if let c = contexts.last, c.ok {
            var objc: String?
            for case .attribute(let a) in node.attributes where Selectors.attributeName(a) == "objc" {
                if case .argumentList(let args)? = a.arguments, let first = args.first {
                    objc = first.expression.trimmedDescription
                } else if case .objCName(let n)? = a.arguments {
                    objc = n.trimmedDescription
                }
            }
            let sup = node.inheritanceClause?.inheritedTypes.first.map { t -> String in
                let s = t.type.trimmedDescription
                return String(s.split(separator: ".").last ?? Substring(s))
            }
            classes.append(Found(qualifiedName: c.name, simpleName: node.name.text, superName: sup, objcName: objc,
                                 conditions: ifConditions(of: node)))
            contexts[contexts.count - 1].index = classes.count - 1
        }
        return .visitChildren
    }
    override func visitPost(_ node: ClassDeclSyntax) { if !isLocalDecl(node) { contexts.removeLast() } }

    override func visit(_ node: InitializerDeclSyntax) -> SyntaxVisitorContinueKind {
        // Initializers in the class body (extensions add convenience ones only).
        guard let c = contexts.last, let i = c.index else { return .skipChildren }
        let labels = node.signature.parameterClause.parameters.compactMap { p -> String? in
            if p.defaultValue != nil { return nil }  // defaulted parameters can be left out
            return p.firstName.text
        }
        classes[i].inits.append(Initializer(
            labels: labels, convenience: node.modifiers.contains { $0.name.text == "convenience" },
            failable: node.optionalMark != nil
                || node.signature.effectSpecifiers?.throwsClause != nil || node.signature.effectSpecifiers?.asyncSpecifier != nil,
            isPrivate: node.modifiers.contains { $0.name.text == "private" || $0.name.text == "fileprivate" }
                || node.attributes.trimmedDescription.contains("unavailable")))
        return .skipChildren
    }

    override func visit(_ node: StructDeclSyntax) -> SyntaxVisitorContinueKind {
        if isLocalDecl(node) { return .skipChildren }
        enter(node.name.text, generic: node.genericParameterClause != nil, modifiers: node.modifiers); return .visitChildren
    }
    override func visitPost(_ node: StructDeclSyntax) { if !isLocalDecl(node) { contexts.removeLast() } }
    override func visit(_ node: EnumDeclSyntax) -> SyntaxVisitorContinueKind {
        if isLocalDecl(node) { return .skipChildren }
        enter(node.name.text, generic: node.genericParameterClause != nil, modifiers: node.modifiers); return .visitChildren
    }
    override func visitPost(_ node: EnumDeclSyntax) { if !isLocalDecl(node) { contexts.removeLast() } }
    override func visit(_ node: ActorDeclSyntax) -> SyntaxVisitorContinueKind { .skipChildren }
    override func visit(_ node: ProtocolDeclSyntax) -> SyntaxVisitorContinueKind { .skipChildren }
    override func visit(_ node: FunctionDeclSyntax) -> SyntaxVisitorContinueKind { .skipChildren }
    override func visit(_ node: VariableDeclSyntax) -> SyntaxVisitorContinueKind { .skipChildren }
    override func visit(_ node: ExtensionDeclSyntax) -> SyntaxVisitorContinueKind {
        // Nested classes in extensions of the module's own types; generic
        // or constrained extensions can't be named simply.
        let name = node.extendedType.trimmedDescription
        let simple = name.allSatisfy { $0.isLetter || $0.isNumber || $0 == "_" || $0 == "." }
        let ok = simple && node.genericWhereClause == nil && !name.hasPrefix("NS") && !name.hasPrefix("Swift.")
            && !generic.contains(String(name.split(separator: ".").last ?? ""))
        contexts.append((name, ok, nil))
        return .visitChildren
    }
    override func visitPost(_ node: ExtensionDeclSyntax) { contexts.removeLast() }
}

private final class GenericTypes: SyntaxVisitor {
    var names: Set<String> = []
    init() { super.init(viewMode: .sourceAccurate) }
    override func visit(_ node: ClassDeclSyntax) -> SyntaxVisitorContinueKind { if node.genericParameterClause != nil { names.insert(node.name.text) }; return .visitChildren }
    override func visit(_ node: StructDeclSyntax) -> SyntaxVisitorContinueKind { if node.genericParameterClause != nil { names.insert(node.name.text) }; return .visitChildren }
    override func visit(_ node: EnumDeclSyntax) -> SyntaxVisitorContinueKind { if node.genericParameterClause != nil { names.insert(node.name.text) }; return .visitChildren }
    override func visit(_ node: FunctionDeclSyntax) -> SyntaxVisitorContinueKind { .skipChildren }
}
