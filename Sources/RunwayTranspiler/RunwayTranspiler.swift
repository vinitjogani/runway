// RunwayTranspiler: rewrites Mac Swift sources that lean on the Objective-C
// runtime so they compile and behave the same without one, against
// RunwayObjC. Runs on every file `runway` stages.
//
//   #selector(save(_:))            → Selector("save:")
//   #keyPath(Doc.title)            → "title"
//   @objc, @objcMembers, @IBAction, @IBOutlet, @NSManaged, dynamic  → removed
//   @objc dynamic var x = 0        → var x = 0 { willSet {KVO…} didSet {KVO…} }
//   classes with selector-reachable members → a generated dispatch table
//   @objc protocol P { @objc optional func f() } → protocol P: AnyObject { func f() } + default
//   d?.f?(x)                       → RunwayObjC.ifResponds(d, Selector("f:"))?.f(x)
//   Timer(timeInterval:target:selector:…) → RunwayObjC.SelectorTimer(…)
//   o.observe(\.a.b, options:…)    → o.observe(\.a.b, _runwayKey: "a.b", options:…)
//   super.observeValue(…) / override func observeValue → for NSObject roots
//   #if os(macOS) / os(OSX)        → #if true;  targetEnvironment(macCatalyst) → false
//   extension V { override func mouseDown(with:) } → moved into class V's body (Relocate.swift)
//
// Edits never add or remove lines in the original text; generated code goes
// after the last line. The one exception, members moved into a class body,
// sits under `#sourceLocation` directives naming each line's original file
// and line. Files that use none of this come back unchanged.

import Foundation
import SwiftParser
import SwiftSyntax

public enum RunwayTranspiler {
    /// Transforms one file. The package around `fileName` (the nearest
    /// directory holding `Sources/`) is scanned once per process for class
    /// hierarchies and selector names; without one, the file stands alone.
    public static func transform(source: String, fileName: String) -> String {
        guard mightNeedWork(source) else { return source }
        let path = URL(fileURLWithPath: fileName).standardizedFileURL.path
        let index = PackageIndexCache.index(for: path, source: source)
        return transform(source: source, fileName: path, index: index)
    }

    /// Transforms one file against an explicit package index (see
    /// `PackageIndex(files:)`). `fileName` must match the path it was indexed under.
    public static func transform(source: String, fileName: String, index: PackageIndex) -> String {
        guard mightNeedWork(source) || index.files[fileName].map({ !$0.members.isEmpty }) == true else { return source }
        let tree = Parser.parse(source: source)
        let bytes = Array(source.utf8)
        let index = index.files[fileName] != nil ? index : index.adding(path: fileName, tree: tree)
        let r = Rewriter(index: index, path: fileName, bytes: bytes)
        r.walk(tree)
        r.generateParts()
        let wantsImport = (r.needsImport || usesRuntimeAPI(source)) && !source.contains("import RunwayObjC")
        var imports = wantsImport ? ["import RunwayObjC"] : []
        for i in r.movedImports where !imports.contains(i) && !(i == "import RunwayObjC" && source.contains("import RunwayObjC")) { imports.append(i) }
        let tail = r.tail + r.notes
        if r.edits.isEmpty && tail.isEmpty && imports.isEmpty { return source }

        var edits = r.finalEdits
        if !imports.isEmpty {
            edits.append(importEdit(tree, bytes, imports))
        }
        var out = apply(edits, to: bytes)
        if !tail.isEmpty {
            if out.last != 0x0A { out.append(0x0A) }
            out += Array("\n// MARK: - Generated by RunwayTranspiler\n".utf8)
            for t in tail { out += Array((t + "\n").utf8) }
        }
        return String(decoding: out, as: UTF8.self)
    }

    /// Cheap check: does the file mention anything this rewrites?
    static func mightNeedWork(_ s: String) -> Bool {
        let needles = ["@objc", "#selector", "dynamic", "@IB", "@NSManaged", "#keyPath", "os(macOS)", "os(OSX)", "macCatalyst",
                       "observe(", "Timer(", "#Preview", "ApplicationDelegateAdaptor", "@Model", "@Entry", "removeObserver", "observeValue", "validate", "?(", "class ", "override", "required", "Darwin.", "ProcessInfo()", "@convention", "]?[", "forKey:",
                       "/Developer/CommandLineTools/usr/bin/", "/Contents/Developer/"]
        return needles.contains { s.contains($0) } || usesRuntimeAPI(s) || importsSubmodule(s)
    }

    /// `import os.log`, `import Carbon.HIToolbox`, `import ObjectiveC`…
    static func importsSubmodule(_ s: String) -> Bool {
        guard s.contains("import ") else { return false }
        for line in s.split(separator: "\n") {
            let t = line.drop { $0 == " " || $0 == "\t" }
            guard t.hasPrefix("import ") else { continue }
            let rest = t.dropFirst(7)
            if rest.hasPrefix("ObjectiveC") { return true }
            if let dot = rest.firstIndex(of: "."), Rewriter.appleSubmoduleParents.contains(String(rest[..<dot])) { return true }
        }
        return false
    }

    /// Runtime API with no rewrite of its own still needs `import RunwayObjC`.
    static func usesRuntimeAPI(_ s: String) -> Bool {
        ["selector:", "perform(", "responds(to", "forKeyPath", "Selector", "value(forKey", "setValue(", "ChangeValue(forKey",
         "NSKeyValue", "cancelPreviousPerformRequests", "performSelector", "ChangeValue(for:", "\"]?[\""].contains { s.contains($0) }
    }

    /// `; import RunwayObjC` (and any other `imports`) after the first
    /// top-level import (or at the very start), keeping every line where it was.
    static func importEdit(_ tree: SourceFileSyntax, _ bytes: [UInt8], _ imports: [String] = ["import RunwayObjC"]) -> Edit {
        for item in tree.statements {
            if let imp = item.item.as(ImportDeclSyntax.self) {
                let at = imp.endPositionBeforeTrailingTrivia.utf8Offset
                return Edit(start: at, end: at, text: imports.map { "; " + $0 }.joined(), seq: -1)
            }
        }
        let text = imports.map { $0 + "; " }.joined()
        let at = tree.statements.first?.positionAfterSkippingLeadingTrivia.utf8Offset ?? 0
        // Before the first statement; `#if` must start its line, so then use the file start.
        if at < bytes.count, bytes[at] == UInt8(ascii: "#") { return Edit(start: 0, end: 0, text: text, seq: -1) }
        return Edit(start: at, end: at, text: text, seq: -1)
    }

    static func apply(_ edits: [Edit], to bytes: [UInt8]) -> [UInt8] {
        let sorted = edits.sorted { ($0.start, $0.seq) < ($1.start, $1.seq) }
        var out: [UInt8] = []
        out.reserveCapacity(bytes.count + 256)
        var pos = 0
        for e in sorted {
            if e.start < pos { continue }  // overlaps an earlier edit: keep the earlier one
            out += bytes[pos..<e.start]
            out += Array(e.text.utf8)
            pos = e.end
        }
        out += bytes[pos...]
        return out
    }
}

extension PackageIndex {
    /// This index plus one more file (one that wasn't on disk when scanned).
    func adding(path: String, tree: SourceFileSyntax) -> PackageIndex {
        let s = Scanner(path: path)
        s.walk(tree)
        return PackageIndex(scans: Array(files.values) + [s.facts], root: root)
    }
}

/// One package index per package root, built on first use.
enum PackageIndexCache {
    private static let lock = NSLock()
    nonisolated(unsafe) private static var cache: [String: PackageIndex] = [:]

    static func index(for fileName: String, source: String) -> PackageIndex {
        guard let root = packageRoot(of: fileName) else {
            return PackageIndex(files: [(fileName, source)])
        }
        lock.lock()
        if let i = cache[root] { lock.unlock(); return i }
        lock.unlock()
        let i = PackageIndex(packageRoot: root)
        lock.lock(); cache[root] = i; lock.unlock()
        return i
    }

    /// The directory above the nearest `Sources` (or `Tests`) ancestor.
    static func packageRoot(of path: String) -> String? {
        var url = URL(fileURLWithPath: path).deletingLastPathComponent()
        while url.path != "/" && !url.path.isEmpty {
            if url.lastPathComponent == "Sources" || url.lastPathComponent == "Tests" {
                let root = url.deletingLastPathComponent().path
                return FileManager.default.fileExists(atPath: path) ? root : nil
            }
            url = url.deletingLastPathComponent()
        }
        return nil
    }
}
