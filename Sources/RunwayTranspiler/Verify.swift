// Checks on transformed output: it parses, and no Objective-C-only syntax
// is left.

import SwiftParser
import SwiftSyntax

public struct TranspileReport: Sendable {
    public var parseErrors: Bool
    /// Remaining `@objc`-family attributes, `#selector`/`#keyPath`, `dynamic`, `optional` in protocols.
    public var leftovers: [String]
    /// Lines of the original that moved (should be none).
    public var linesShifted: Bool
}

extension RunwayTranspiler {
    /// Verifies `output` (the transform of `original`).
    public static func verify(original: String, output: String) -> TranspileReport {
        let tree = Parser.parse(source: output)
        let v = LeftoverFinder(viewMode: .sourceAccurate)
        v.walk(tree)
        let origLines = original.split(separator: "\n", omittingEmptySubsequences: false).count
        let outLines = withoutMovedBlocks(output.split(separator: "\n", omittingEmptySubsequences: false))
        // Every generated line comes after the marker, which follows the original's last line.
        var shifted = false
        if let marker = outLines.firstIndex(where: { $0 == "// MARK: - Generated by RunwayTranspiler" }) {
            shifted = marker + 1 > origLines + 2
        } else {
            shifted = outLines.count != origLines
        }
        return TranspileReport(parseErrors: tree.hasError, leftovers: v.found, linesShifted: shifted)
    }
}

/// The lines with each block of overrides moved into a class body (see
/// Relocate.swift) taken out, and the closing brace it pushed down joined
/// back to the line it came from.
func withoutMovedBlocks(_ lines: [Substring]) -> [Substring] {
    var out: [Substring] = []
    var i = 0
    while i < lines.count {
        if lines[i] == Relocate.beginMarker, !out.isEmpty,
           let end = lines[i...].firstIndex(of: Substring(Relocate.endMarker)), end + 2 < lines.count {
            let brace = lines[end + 2]
            let prev = out.removeLast()
            out.append(Substring(String(prev) + brace.drop { $0 == " " }))
            i = end + 3
            continue
        }
        out.append(lines[i])
        i += 1
    }
    return out
}

final class LeftoverFinder: SyntaxVisitor {
    var found: [String] = []
    override func visit(_ node: AttributeSyntax) -> SyntaxVisitorContinueKind {
        let n = Selectors.attributeName(node)
        if strippedAttributes.contains(n) { found.append("@" + n) }
        return .skipChildren
    }
    override func visit(_ node: DeclModifierSyntax) -> SyntaxVisitorContinueKind {
        if node.name.text == "dynamic" { found.append("dynamic") }
        return .skipChildren
    }
    override func visit(_ node: MacroExpansionExprSyntax) -> SyntaxVisitorContinueKind {
        if node.macroName.text == "selector" || node.macroName.text == "keyPath" { found.append("#" + node.macroName.text) }
        return .visitChildren
    }
}
