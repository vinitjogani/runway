enum Layout {
    /// kVK code → (unshifted, shifted) characters on a US ANSI keyboard (CoreServices' table).
    static var characters: [Int: (String, String)] { _USKeyboardLayout.characters }

    /// kVK code → X11 keysym.
    static func keysym(_ code: Int) -> UInt? {
        let special: [Int: UInt] = [
            0x24: 0xff0d, 0x30: 0xff09, 0x31: 0x20, 0x33: 0xff08, 0x35: 0xff1b, 0x75: 0xffff, 0x73: 0xff50, 0x77: 0xff57,
            0x74: 0xff55, 0x79: 0xff56, 0x7B: 0xff51, 0x7E: 0xff52, 0x7C: 0xff53, 0x7D: 0xff54, 0x72: 0xff63, 0x47: 0xff0b,
            0x7A: 0xffbe, 0x78: 0xffbf, 0x63: 0xffc0, 0x76: 0xffc1, 0x60: 0xffc2, 0x61: 0xffc3, 0x62: 0xffc4, 0x64: 0xffc5,
            0x65: 0xffc6, 0x6D: 0xffc7, 0x67: 0xffc8, 0x6F: 0xffc9, 0x69: 0xffca, 0x6B: 0xffcb, 0x71: 0xffcc, 0x6A: 0xffcd,
            0x40: 0xffce, 0x4F: 0xffcf, 0x50: 0xffd0, 0x5A: 0xffd1,
            0x52: 0xffb0, 0x53: 0xffb1, 0x54: 0xffb2, 0x55: 0xffb3, 0x56: 0xffb4, 0x57: 0xffb5, 0x58: 0xffb6, 0x59: 0xffb7,
            0x5B: 0xffb8, 0x5C: 0xffb9, 0x41: 0xffae, 0x43: 0xffaa, 0x45: 0xffab, 0x4B: 0xffaf, 0x4C: 0xff8d, 0x4E: 0xffad,
            0x51: 0xffbd, 0x48: 0x1008ff13, 0x49: 0x1008ff11, 0x4A: 0x1008ff12, 0x6E: 0xff67,
        ]
        if let s = special[code] { return s }
        guard let c = characters[code]?.0.unicodeScalars.first, c.value < 0x7f else { return nil }
        return UInt(c.value)
    }

    /// kVK code → Windows virtual-key code.
    static func windowsVK(_ code: Int) -> UInt32? {
        if let ch = characters[code]?.1.unicodeScalars.first, ("A"..."Z").contains(ch) || ("0"..."9").contains(ch), code < 0x41 {
            return ch.value
        }
        if let ch = characters[code]?.0.unicodeScalars.first, ("0"..."9").contains(ch), code < 0x41 { return ch.value }
        let map: [Int: UInt32] = [
            0x24: 0x0D, 0x30: 0x09, 0x31: 0x20, 0x33: 0x08, 0x35: 0x1B, 0x75: 0x2E, 0x73: 0x24, 0x77: 0x23, 0x74: 0x21, 0x79: 0x22,
            0x7B: 0x25, 0x7E: 0x26, 0x7C: 0x27, 0x7D: 0x28, 0x72: 0x2D, 0x7A: 0x70, 0x78: 0x71, 0x63: 0x72, 0x76: 0x73, 0x60: 0x74,
            0x61: 0x75, 0x62: 0x76, 0x64: 0x77, 0x65: 0x78, 0x6D: 0x79, 0x67: 0x7A, 0x6F: 0x7B, 0x18: 0xBB, 0x1B: 0xBD, 0x21: 0xDB,
            0x1E: 0xDD, 0x29: 0xBA, 0x27: 0xDE, 0x2B: 0xBC, 0x2F: 0xBE, 0x2C: 0xBF, 0x2A: 0xDC, 0x32: 0xC0,
        ]
        return map[code]
    }
}
