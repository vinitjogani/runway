@preconcurrency @MainActor public final class NSLayoutDimension: NSLayoutAnchor<NSLayoutDimension> {
    override init(_ item: LayoutItem, _ a: NSLayoutConstraint.Attribute) { super.init(item, a) }
    /// The distance between two anchors (`anchorWithOffset(to:)`), as a
    /// dimension backed by a hidden guide.
    convenience init<T>(offsetFrom a: NSLayoutAnchor<T>, to b: NSLayoutAnchor<T>) {
        let guide = NSLayoutGuide()
        let owner = a.item.owningView ?? b.item.owningView
        owner?.addLayoutGuide(guide)
        let vertical = a.attribute == .top || a.attribute == .bottom || a.attribute == .centerY || a.attribute == .firstBaseline || a.attribute == .lastBaseline
        self.init(guide.layoutItem, vertical ? .height : .width)
        let start = NSLayoutConstraint(item: guide, attribute: vertical ? .top : .left, relatedBy: .equal, toItem: a.item.target, attribute: a.attribute, multiplier: 1, constant: 0)
        let end = NSLayoutConstraint(item: guide, attribute: vertical ? .bottom : .right, relatedBy: .equal, toItem: b.item.target, attribute: b.attribute, multiplier: 1, constant: 0)
        start.isInternal = true; end.isInternal = true
        NSLayoutConstraint.activate([start, end])
    }
    public func constraint(equalToConstant c: CGFloat) -> NSLayoutConstraint { make(.equal, nil, 1, c) }
    public func constraint(greaterThanOrEqualToConstant c: CGFloat) -> NSLayoutConstraint { make(.greaterThanOrEqual, nil, 1, c) }
    public func constraint(lessThanOrEqualToConstant c: CGFloat) -> NSLayoutConstraint { make(.lessThanOrEqual, nil, 1, c) }
    public func constraint(equalTo anchor: NSLayoutDimension, multiplier m: CGFloat) -> NSLayoutConstraint { make(.equal, anchor, m, 0) }
    public func constraint(equalTo anchor: NSLayoutDimension, multiplier m: CGFloat, constant c: CGFloat) -> NSLayoutConstraint { make(.equal, anchor, m, c) }
    public func constraint(greaterThanOrEqualTo anchor: NSLayoutDimension, multiplier m: CGFloat) -> NSLayoutConstraint { make(.greaterThanOrEqual, anchor, m, 0) }
    public func constraint(greaterThanOrEqualTo anchor: NSLayoutDimension, multiplier m: CGFloat, constant c: CGFloat) -> NSLayoutConstraint { make(.greaterThanOrEqual, anchor, m, c) }
    public func constraint(lessThanOrEqualTo anchor: NSLayoutDimension, multiplier m: CGFloat) -> NSLayoutConstraint { make(.lessThanOrEqual, anchor, m, 0) }
    public func constraint(lessThanOrEqualTo anchor: NSLayoutDimension, multiplier m: CGFloat, constant c: CGFloat) -> NSLayoutConstraint { make(.lessThanOrEqual, anchor, m, c) }
}

// MARK: Layout items (views and guides)

/// A view's or guide's solver variables and anchors.
@MainActor final class LayoutItem {
    weak var view: NSView?
    weak var guide: NSLayoutGuide?
    let x = CassowarySolver.Variable("x"), y = CassowarySolver.Variable("y")
    let w = CassowarySolver.Variable("w"), h = CassowarySolver.Variable("h")
    init(view: NSView) { self.view = view }
    init(guide: NSLayoutGuide) { self.guide = guide }

    var target: AnyObject? { view ?? guide }
    /// The view whose hierarchy the item lives in.
    var owningView: NSView? { view ?? guide?.owningView }

    static func of(_ o: AnyObject) -> LayoutItem? {
        if let v = o as? NSView { return v.layoutItem }
        if let g = o as? NSLayoutGuide { return g.layoutItem }
        return nil
    }
    static func owningView(_ o: AnyObject) -> NSView? { of(o)?.owningView }
    /// For conflict reports: the item's class and identifier.
    var debugName: String {
        if let v = view { return "\(type(of: v))" + (v.identifier.map { " '\($0.rawValue)'" } ?? "") }
        if guide != nil { return "a layout guide" }
        return "an item"
    }

    lazy var leading = NSLayoutXAxisAnchor(self, .leading)
    lazy var trailing = NSLayoutXAxisAnchor(self, .trailing)
    lazy var left = NSLayoutXAxisAnchor(self, .left)
    lazy var right = NSLayoutXAxisAnchor(self, .right)
    lazy var centerX = NSLayoutXAxisAnchor(self, .centerX)
    lazy var top = NSLayoutYAxisAnchor(self, .top)
    lazy var bottom = NSLayoutYAxisAnchor(self, .bottom)
    lazy var centerY = NSLayoutYAxisAnchor(self, .centerY)
    lazy var firstBaseline = NSLayoutYAxisAnchor(self, .firstBaseline)
    lazy var lastBaseline = NSLayoutYAxisAnchor(self, .lastBaseline)
    lazy var width = NSLayoutDimension(self, .width)
    lazy var height = NSLayoutDimension(self, .height)

    func anchor(_ a: NSLayoutConstraint.Attribute) -> AnyObject? {
        switch a {
        case .leading: leading
        case .trailing: trailing
        case .left: left
        case .right: right
        case .centerX: centerX
        case .top: top
        case .bottom: bottom
        case .centerY: centerY
        case .firstBaseline: firstBaseline
        case .lastBaseline: lastBaseline
        case .width: width
        case .height: height
        case .notAnAttribute: nil
        }
    }

    /// The attribute as a linear expression of the item's variables.
    func expression(_ a: NSLayoutConstraint.Attribute) -> CassowarySolver.Expression {
        typealias E = CassowarySolver.Expression
        typealias T = CassowarySolver.Term
        switch a {
        case .left, .leading: return E([T(variable: x, coefficient: 1)])
        case .right, .trailing: return E([T(variable: x, coefficient: 1), T(variable: w, coefficient: 1)])
        case .top: return E([T(variable: y, coefficient: 1)])
        case .bottom: return E([T(variable: y, coefficient: 1), T(variable: h, coefficient: 1)])
        case .centerX: return E([T(variable: x, coefficient: 1), T(variable: w, coefficient: 0.5)])
        case .centerY: return E([T(variable: y, coefficient: 1), T(variable: h, coefficient: 0.5)])
        case .width: return E([T(variable: w, coefficient: 1)])
        case .height: return E([T(variable: h, coefficient: 1)])
        case .firstBaseline:
            return E([T(variable: y, coefficient: 1)], Double(view?.firstBaselineOffsetFromTop ?? 0))
        case .lastBaseline:
            return E([T(variable: y, coefficient: 1), T(variable: h, coefficient: 1)], -Double(view?.lastBaselineOffsetFromBottom ?? 0))
        case .notAnAttribute: return E()
        }
    }

    var solvedRect: CGRect { CGRect(x: x.value, y: y.value, width: w.value, height: h.value) }
}

@preconcurrency @MainActor
open class NSLayoutGuide: NSObject, NSUserInterfaceItemIdentification {
    open weak var owningView: NSView? { didSet { owningView?.layoutRoot.layoutStructureChangedOnRoot() } }
    open var identifier: NSUserInterfaceItemIdentifier?
    lazy var layoutItem = LayoutItem(guide: self)
    public override init() { super.init() }

    /// The guide's rectangle in the owning view's coordinates.
    open var frame: NSRect {
        guard let v = owningView, let e = v.layoutRoot.engine, e.contains(layoutItem) else { return .zero }
        v.layoutRoot.layoutSubtreeIfNeeded()
        return e.frame(of: layoutItem, in: v)
    }
    open var leadingAnchor: NSLayoutXAxisAnchor { layoutItem.leading }
    open var trailingAnchor: NSLayoutXAxisAnchor { layoutItem.trailing }
    open var leftAnchor: NSLayoutXAxisAnchor { layoutItem.left }
    open var rightAnchor: NSLayoutXAxisAnchor { layoutItem.right }
    open var centerXAnchor: NSLayoutXAxisAnchor { layoutItem.centerX }
    open var topAnchor: NSLayoutYAxisAnchor { layoutItem.top }
    open var bottomAnchor: NSLayoutYAxisAnchor { layoutItem.bottom }
    open var centerYAnchor: NSLayoutYAxisAnchor { layoutItem.centerY }
    open var widthAnchor: NSLayoutDimension { layoutItem.width }
    open var heightAnchor: NSLayoutDimension { layoutItem.height }
    open var hasAmbiguousLayout: Bool { false }
    open func constraintsAffectingLayout(for o: NSLayoutConstraint.Orientation) -> [NSLayoutConstraint] {
        owningView?.constraints.filter { $0.firstItem === self || $0.secondItem === self } ?? []
    }
}

// MARK: NSView's Auto Layout API

extension NSView {
    public var leadingAnchor: NSLayoutXAxisAnchor { layoutItem.leading }
    public var trailingAnchor: NSLayoutXAxisAnchor { layoutItem.trailing }
    public var leftAnchor: NSLayoutXAxisAnchor { layoutItem.left }
    public var rightAnchor: NSLayoutXAxisAnchor { layoutItem.right }
    public var centerXAnchor: NSLayoutXAxisAnchor { layoutItem.centerX }
    public var topAnchor: NSLayoutYAxisAnchor { layoutItem.top }
    public var bottomAnchor: NSLayoutYAxisAnchor { layoutItem.bottom }
    public var centerYAnchor: NSLayoutYAxisAnchor { layoutItem.centerY }
    public var firstBaselineAnchor: NSLayoutYAxisAnchor { layoutItem.firstBaseline }
    public var lastBaselineAnchor: NSLayoutYAxisAnchor { layoutItem.lastBaseline }
    public var widthAnchor: NSLayoutDimension { layoutItem.width }
    public var heightAnchor: NSLayoutDimension { layoutItem.height }

    /// The constraints installed on this view (user-made ones).
    public var constraints: [NSLayoutConstraint] { _constraints.filter { !$0.isInternal } }
    public func addConstraint(_ c: NSLayoutConstraint) {
        if let o = c.owner, o !== self { o.removeConstraint(c) }
        guard c.owner == nil else { return }
        c.owner = self
        _constraints.append(c)
        layoutStructureChanged()
    }
    public func addConstraints(_ cs: [NSLayoutConstraint]) { for c in cs { addConstraint(c) } }
    public func removeConstraint(_ c: NSLayoutConstraint) {
        guard c.owner === self else { return }
        _constraints.removeAll { $0 === c }
        c.owner = nil
        layoutStructureChanged()
    }
    public func removeConstraints(_ cs: [NSLayoutConstraint]) { for c in cs { removeConstraint(c) } }

    /// Constraints on ancestors that reference this view's subtree (made
    /// inactive when the subtree leaves).
    func constraintsInvolvingOutside() -> [NSLayoutConstraint] {
        var out: [NSLayoutConstraint] = []
        var ids = Set<ObjectIdentifier>()
        func collect(_ v: NSView) { ids.insert(ObjectIdentifier(v)); v._layoutGuides.forEach { ids.insert(ObjectIdentifier($0)) }; v.subviews.forEach(collect) }
        collect(self)
        var a = superview
        while let cur = a {
            for c in cur._constraints {
                let f = c.firstItem.map { ids.contains(ObjectIdentifier($0)) } ?? false
                let s = c.secondItem.map { ids.contains(ObjectIdentifier($0)) } ?? false
                if f || s { out.append(c) }
            }
            a = cur.superview
        }
        return out
    }

    public var layoutGuides: [NSLayoutGuide] { _layoutGuides }
    public func addLayoutGuide(_ g: NSLayoutGuide) {
        guard !_layoutGuides.contains(where: { $0 === g }) else { return }
        _layoutGuides.append(g)
        g.owningView = self
    }
    public func removeLayoutGuide(_ g: NSLayoutGuide) {
        _layoutGuides.removeAll { $0 === g }
        for c in _constraints where c.firstItem === g || c.secondItem === g { removeConstraint(c) }
        g.owningView = nil
    }

    /// How far window chrome (a toolbar band over full-size content) and
    /// the views' additional insets reach into this view, from each edge.
    public var safeAreaInsets: NSEdgeInsets {
        var top: CGFloat = 0, left: CGFloat = 0, bottom: CGFloat = 0, right: CGFloat = 0
        if let s = superview {
            // The part of the superview's safe rectangle this view leaves out.
            let p = s.safeAreaInsets
            if p.top > 0 || p.left > 0 || p.bottom > 0 || p.right > 0 {
                let b = s.bounds, f = frame
                let safeMinY = s.isFlipped ? b.minY + p.top : b.minY + p.bottom
                let safeMaxY = s.isFlipped ? b.maxY - p.bottom : b.maxY - p.top
                let below = max(0, min(f.height, safeMinY - f.minY)), above = max(0, min(f.height, f.maxY - safeMaxY))
                top = s.isFlipped ? below : above
                bottom = s.isFlipped ? above : below
                left = max(0, min(f.width, b.minX + p.left - f.minX))
                right = max(0, min(f.width, f.maxX - (b.maxX - p.right)))
            }
        } else if let w = window, w.contentView === self {
            top = w.titlebarInset
        }
        let a = _additionalSafeAreaInsets
        return NSEdgeInsets(top: top + a.top, left: left + a.left, bottom: bottom + a.bottom, right: right + a.right)
    }
    /// The bounds less the safe area's insets.
    public var safeAreaRect: NSRect {
        let i = safeAreaInsets, b = bounds
        return CGRect(x: b.minX + i.left, y: b.minY + (isFlipped ? i.top : i.bottom),
                      width: max(0, b.width - i.left - i.right), height: max(0, b.height - i.top - i.bottom))
    }
    public var additionalSafeAreaInsets: NSEdgeInsets {
        get { _additionalSafeAreaInsets }
        set { _additionalSafeAreaInsets = newValue; safeAreaMayHaveChanged() }
    }
    public var safeAreaLayoutGuide: NSLayoutGuide {
        let ident = NSUserInterfaceItemIdentifier("_runway.safeArea")
        if let g = _layoutGuides.first(where: { $0.identifier == ident }) { return g }
        let g = builtInGuide("safeArea", inset: NSEdgeInsets())
        SafeArea.track(self, guide: g)
        return g
    }

    /// Window chrome or a frame changed: the safe areas under this view's
    /// root follow on its next layout pass (now, if it has a window).
    func safeAreaMayHaveChanged() {
        let root = layoutRoot
        if SafeArea.update(under: root) { root.needsLayout = true }
    }
    /// The standard margins (20 points), as a guide.
    public var layoutMarginsGuide: NSLayoutGuide { builtInGuide("layoutMargins", inset: NSEdgeInsets(top: 20, left: 20, bottom: 20, right: 20)) }

    private func builtInGuide(_ id: String, inset: NSEdgeInsets) -> NSLayoutGuide {
        let ident = NSUserInterfaceItemIdentifier("_runway." + id)
        if let g = _layoutGuides.first(where: { $0.identifier == ident }) { return g }
        let g = NSLayoutGuide()
        g.identifier = ident
        addLayoutGuide(g)
        let cs = [
            g.leadingAnchor.constraint(equalTo: leadingAnchor, constant: inset.left),
            g.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -inset.right),
            g.topAnchor.constraint(equalTo: topAnchor, constant: inset.top),
            g.bottomAnchor.constraint(equalTo: bottomAnchor, constant: -inset.bottom),
        ]
        for c in cs { c.isInternal = true; addConstraint(c) }
        return g
    }

    public func invalidateIntrinsicContentSize() {
        let root = layoutRoot
        root.engine?.itemChanged(self)
        root.needsLayout = true
    }
    public func contentHuggingPriority(for o: NSLayoutConstraint.Orientation) -> NSLayoutConstraint.Priority { o == .horizontal ? hugging.h : hugging.v }
    public func setContentHuggingPriority(_ p: NSLayoutConstraint.Priority, for o: NSLayoutConstraint.Orientation) {
        if o == .horizontal { hugging.h = p } else { hugging.v = p }
        invalidateIntrinsicContentSize()
    }
    public func contentCompressionResistancePriority(for o: NSLayoutConstraint.Orientation) -> NSLayoutConstraint.Priority { o == .horizontal ? compression.h : compression.v }
    public func setContentCompressionResistancePriority(_ p: NSLayoutConstraint.Priority, for o: NSLayoutConstraint.Orientation) {
        if o == .horizontal { compression.h = p } else { compression.v = p }
        invalidateIntrinsicContentSize()
    }
    public func alignmentRect(forFrame f: NSRect) -> NSRect { f }
    public func frame(forAlignmentRect r: NSRect) -> NSRect { r }

    // The layout pass.

    /// The top of this view's hierarchy (where its layout engine lives).
    var layoutRoot: NSView {
        var v = self
        while let s = v.superview { v = s }
        return v
    }

    public func updateConstraintsForSubtreeIfNeeded() {
        for s in subviews { s.updateConstraintsForSubtreeIfNeeded() }
        if _needsUpdateConstraints {
            if let vc = _viewController, vc.isViewLoaded, vc.view === self { vc.updateViewConstraints() } else { updateConstraints() }
            _needsUpdateConstraints = false
        }
    }

    /// AppKit's default layout(): applies the constraint solution to
    /// subviews that don't translate their autoresizing masks.
    func applyEngineFrames() {
        guard let e = layoutRoot.engine, !e.isEmpty else { return }
        e.solveIfNeeded()
        for s in subviews where !s.translatesAutoresizingMaskIntoConstraints && e.contains(s.layoutItem) {
            let f = e.frame(of: s.layoutItem, in: self)
            if s.frame != f { s.frame = f }
        }
    }

    /// Updates constraints and lays out this view's subtree now.
    public func layoutSubtreeIfNeeded() {
        let root = layoutRoot
        for _ in 0..<6 {
            root.updateConstraintsForSubtreeIfNeeded()
            if root.engine == nil, root.subtreeUsesConstraints() { root.engine = LayoutEngine(root: root) }
            if let e = root.engine { e.solveIfNeeded() }
            var any = false
            root.layoutPass(&any)
            // Frames moved: safe areas (and the guides that follow them) too.
            if SafeArea.update(under: root) { continue }
            if !any && !(root.engine?.isDirty ?? false) { break }
        }
    }

    private func layoutPass(_ any: inout Bool) {
        if _needsLayout || (layoutRoot.engine?.consumeFramesChanged(under: self) ?? false) {
            _needsLayout = false
            any = true
            let vc = _viewController?.view === self ? _viewController : nil
            vc?.viewWillLayout()
            layout()
            vc?.viewDidLayout()
        }
        for s in subviews { s.layoutPass(&any) }
    }

    func subtreeUsesConstraints() -> Bool {
        if !_constraints.isEmpty { return true }
        return subviews.contains { $0.subtreeUsesConstraints() }
    }

    /// The smallest size satisfying the constraints this view's subtree holds.
    func computeFittingSize() -> NSSize {
        guard subtreeUsesConstraints() else {
            let i = intrinsicContentSize
            if i.width >= 0 || i.height >= 0 { return NSSize(width: max(0, i.width), height: max(0, i.height)) }
            return frame.size
        }
        updateConstraintsForSubtreeIfNeeded()
        let e = LayoutEngine(root: self, fitting: true)
        e.solveIfNeeded()
        let r = e.rootItem.solvedRect
        return NSSize(width: r.width.rounded(.up), height: r.height.rounded(.up))
    }

    public var hasAmbiguousLayout: Bool { false }
    public func exerciseAmbiguityInLayout() {}
    public func constraintsAffectingLayout(for o: NSLayoutConstraint.Orientation) -> [NSLayoutConstraint] {
        var out: [NSLayoutConstraint] = []
        var v: NSView? = self
        while let cur = v {
            out += cur.constraints.filter { $0.firstItem === self || $0.secondItem === self }
            v = cur.superview
        }
        return out
    }

    func layoutStructureChanged() {
        layoutRoot.layoutStructureChangedOnRoot()
    }
    func layoutStructureChangedOnRoot() {
        engine?.structureDirty = true
        if engine != nil || subtreeUsesConstraints() { needsLayout = true }
    }
    /// A translating view's frame moved: its pins change.
    func layoutConstantsChanged() {
        let root = layoutRoot
        guard let e = root.engine, !e.isEmpty, root !== self || true else { return }
        if root === self { e.rootSizeChanged() } else { e.itemChanged(self) }
        if !ViewSystem.flushing || !e.applying { root.needsLayout = true }
    }
}

// MARK: The engine

@MainActor final class LayoutEngine {
    unowned let root: NSView
    let rootItem: LayoutItem
    private var solver = CassowarySolver()
    private let fitting: Bool
    var structureDirty = true
    private var dirtyConstraints: [NSLayoutConstraint] = []
    private var dirtyItems: [ObjectIdentifier: LayoutItem] = [:]
    private var rootDirty = false
    private var solvedDirty = true
    var applying = false
    private(set) var isEmpty = true

    private var members: [ObjectIdentifier: LayoutItem] = [:]
    private var installed: [ObjectIdentifier: (NSLayoutConstraint, CassowarySolver.Constraint)] = [:]
    private var generated: [ObjectIdentifier: [CassowarySolver.Constraint]] = [:]
    private var lastSolved: [ObjectIdentifier: CGRect] = [:]
    private var changedParents = Set<ObjectIdentifier>()

    init(root: NSView, fitting: Bool = false) {
        self.root = root
        rootItem = root.layoutItem
        self.fitting = fitting
    }

    var isDirty: Bool { structureDirty || !dirtyConstraints.isEmpty || !dirtyItems.isEmpty || rootDirty }
    func contains(_ item: LayoutItem) -> Bool {
        if structureDirty { solveIfNeeded() }
        return members[ObjectIdentifier(item)] != nil
    }

    func constraintChanged(_ c: NSLayoutConstraint) { dirtyConstraints.append(c) }
    func itemChanged(_ v: NSView) { dirtyItems[ObjectIdentifier(v.layoutItem)] = v.layoutItem }
    func rootSizeChanged() { rootDirty = true }

    /// Whether solving moved any of `view`'s subviews.
    func consumeFramesChanged(under view: NSView) -> Bool { changedParents.remove(ObjectIdentifier(view)) != nil }

    func solveIfNeeded() {
        if structureDirty { rebuild() } else if isDirty { update() } else if !solvedDirty { return }
        solvedDirty = false
        solver.updateVariables()
        changedParents.removeAll()
        for (id, item) in members {
            let r = item.solvedRect
            if lastSolved[id] != r {
                lastSolved[id] = r
                if let v = item.view, let s = v.superview { changedParents.insert(ObjectIdentifier(s)) }
            }
        }
    }

    /// Conflicts broken so far (tests read it).
    static var conflicts: [String] = []

    /// Adds `c`, returning what's in the solver for it (to remove later).
    @discardableResult
    private func add(_ c: CassowarySolver.Constraint, _ what: @autoclosure () -> String) -> CassowarySolver.Constraint {
        do { try solver.add(c) } catch {
            if c.isRequired {
                // AppKit breaks one constraint and logs; so do we, retrying it
                // just below required.
                let message = "unable to simultaneously satisfy constraints; breaking \(what())"
                Self.conflicts.append(message)
                FileHandle.standardError.write(Data("runway: \(message)\n".utf8))
                let weaker = CassowarySolver.Constraint(c.expression, c.relation, strength: NSLayoutConstraint.Priority(999).strength)
                try? solver.add(weaker)
                return weaker
            }
        }
        return c
    }

    private func toSolver(_ c: NSLayoutConstraint) -> CassowarySolver.Constraint? {
        guard let a = c.firstItem.flatMap(LayoutItem.of) else { return nil }
        var e = a.expression(c.firstAttribute)
        if let s = c.secondItem.flatMap(LayoutItem.of), c.secondAttribute != .notAnAttribute {
            e = e - s.expression(c.secondAttribute) * Double(c.multiplier)
        }
        e = e + -Double(c.constant)
        let rel: CassowarySolver.Relation = c.relation == .equal ? .equal : c.relation == .lessThanOrEqual ? .lessOrEqual : .greaterOrEqual
        return CassowarySolver.Constraint(e, rel, strength: c.priority.strength)
    }

    private func rebuild() {
        structureDirty = false
        solver = CassowarySolver()
        members.removeAll(); installed.removeAll(); generated.removeAll()
        dirtyConstraints.removeAll(); dirtyItems.removeAll(); rootDirty = false
        lastSolved.removeAll()
        // The constraints in the hierarchy.
        var all: [NSLayoutConstraint] = []
        var inTree = Set<ObjectIdentifier>()
        func walk(_ v: NSView) {
            inTree.insert(ObjectIdentifier(v))
            for g in v._layoutGuides { inTree.insert(ObjectIdentifier(g)) }
            all += v._constraints
            for s in v.subviews { walk(s) }
        }
        walk(root)
        // Members: constrained items, and their views' ancestors.
        func addMember(_ item: LayoutItem) {
            guard members[ObjectIdentifier(item)] == nil else { return }
            members[ObjectIdentifier(item)] = item
            if let v = item.view, v !== root, let s = v.superview { addMember(s.layoutItem) }
            if let g = item.guide, let v = g.owningView { addMember(v.layoutItem) }
        }
        addMember(rootItem)
        var usable: [NSLayoutConstraint] = []
        for c in all {
            guard let f = c.firstItem, inTree.contains(ObjectIdentifier(f)) else { continue }
            if let s = c.secondItem, !inTree.contains(ObjectIdentifier(s)) { continue }
            usable.append(c)
            LayoutItem.of(f).map(addMember)
            if let s = c.secondItem { LayoutItem.of(s).map(addMember) }
        }
        isEmpty = usable.isEmpty
        for c in usable {
            if let sc = toSolver(c) {
                installed[ObjectIdentifier(c)] = (c, add(sc, c.description))
            }
        }
        for item in members.values.sorted(by: { ObjectIdentifier($0) < ObjectIdentifier($1) }) { generate(item) }
        solvedDirty = true
    }

    private func update() {
        for c in dirtyConstraints {
            guard let (_, old) = installed[ObjectIdentifier(c)] else { continue }
            try? solver.remove(old)
            if let sc = toSolver(c) {
                installed[ObjectIdentifier(c)] = (c, add(sc, c.description))
            }
        }
        dirtyConstraints.removeAll()
        for item in dirtyItems.values where members[ObjectIdentifier(item)] != nil {
            for c in generated[ObjectIdentifier(item)] ?? [] { try? solver.remove(c) }
            generate(item)
        }
        dirtyItems.removeAll()
        if rootDirty {
            rootDirty = false
            for c in generated[ObjectIdentifier(rootItem)] ?? [] { try? solver.remove(c) }
            generate(rootItem)
        }
        solvedDirty = true
    }

    /// The generated constraints of one item: the root's size, autoresizing
    /// pins, intrinsic size.
    private func generate(_ item: LayoutItem) {
        typealias C = CassowarySolver.Constraint
        typealias E = CassowarySolver.Expression
        typealias T = CassowarySolver.Term
        func v(_ x: CassowarySolver.Variable, _ k: Double = 1) -> T { T(variable: x, coefficient: k) }
        var out: [C] = []
        let required = CassowarySolver.required
        if item === rootItem {
            out.append(C(E([v(item.x)]), .equal, strength: required))
            out.append(C(E([v(item.y)]), .equal, strength: required))
            let size = root.frame.size
            let strength = fitting ? NSLayoutConstraint.Priority.fittingSizeCompression.strength : NSLayoutConstraint.Priority(999.5).strength
            out.append(C(E([v(item.w)], -Double(fitting ? 0 : size.width)), .equal, strength: strength))
            out.append(C(E([v(item.h)], -Double(fitting ? 0 : size.height)), .equal, strength: strength))
            out.append(C(E([v(item.w)]), .greaterOrEqual, strength: required))
            out.append(C(E([v(item.h)]), .greaterOrEqual, strength: required))
        } else if let view = item.view, let parent = view.superview {
            let p = parent.layoutItem
            if view.translatesAutoresizingMaskIntoConstraints {
                let f = view.frame, b = parent.bounds
                out.append(C(E([v(item.x), v(p.x, -1)], -Double(f.minX - b.minX)), .equal, strength: required))
                if parent.isFlipped {
                    out.append(C(E([v(item.y), v(p.y, -1)], -Double(f.minY - b.minY)), .equal, strength: required))
                } else {
                    // y = parent.y + parent.h - (maxY - bounds.minY)
                    out.append(C(E([v(item.y), v(p.y, -1), v(p.h, -1)], Double(f.maxY - b.minY)), .equal, strength: required))
                }
                // A stack view sizes its arranged views from their own
                // constraints (AppKit's stack constrains them, so they
                // don't translate a frame there): until it next arranges
                // them, their frame's size is only a proposal.
                let arranged = (parent as? NSStackView)?.arrangedSubviews.contains { $0 === view } ?? false
                let sizeStrength = arranged ? NSLayoutConstraint.Priority(999).strength : required
                out.append(C(E([v(item.w)], -Double(f.width)), .equal, strength: sizeStrength))
                out.append(C(E([v(item.h)], -Double(f.height)), .equal, strength: sizeStrength))
            } else {
                let i = view.intrinsicContentSize
                if i.width != NSView.noIntrinsicMetric {
                    out.append(C(E([v(item.w)], -Double(i.width)), .greaterOrEqual, strength: view.compression.h.strength))
                    out.append(C(E([v(item.w)], -Double(i.width)), .lessOrEqual, strength: view.hugging.h.strength))
                }
                if i.height != NSView.noIntrinsicMetric {
                    out.append(C(E([v(item.h)], -Double(i.height)), .greaterOrEqual, strength: view.compression.v.strength))
                    out.append(C(E([v(item.h)], -Double(i.height)), .lessOrEqual, strength: view.hugging.v.strength))
                }
                out.append(C(E([v(item.w)]), .greaterOrEqual, strength: required))
                out.append(C(E([v(item.h)]), .greaterOrEqual, strength: required))
            }
        }
        let isRoot = item === rootItem
        func what() -> String {
            let kind = isRoot ? "the root's size"
                : item.view?.translatesAutoresizingMaskIntoConstraints == true ? "its autoresizing frame \(item.view!.frame)" : "its intrinsic size"
            return "a generated constraint of \(item.debugName) (\(kind))"
        }
        generated[ObjectIdentifier(item)] = out.map { add($0, what()) }
    }

    /// An item's solved rectangle in `view`'s coordinates (a superview or
    /// the guide's owner).
    func frame(of item: LayoutItem, in view: NSView) -> CGRect {
        solveIfNeeded()
        let r = item.solvedRect
        let p = view.layoutItem.solvedRect
        let b = view.bounds
        let x = r.minX - p.minX + b.minX
        let y = view.isFlipped ? r.minY - p.minY + b.minY : p.height - (r.minY - p.minY) - r.height + b.minY
        return CGRect(x: x, y: y, width: max(0, r.width), height: max(0, r.height))
    }
}

// MARK: The visual format language

@MainActor enum VisualFormat {
    static let siblingSpacing: CGFloat = 8
    static let superviewSpacing: CGFloat = 20

    struct Predicate { var relation: NSLayoutConstraint.Relation; var constant: CGFloat?; var view: String?; var priority: Float? }

    static func parse(_ format: String, options: NSLayoutConstraint.FormatOptions, metrics: [String: Any], views: [String: Any]) -> [NSLayoutConstraint] {
        var s = Substring(format.filter { !$0.isWhitespace })
        var vertical = false
        if s.hasPrefix("V:") { vertical = true; s = s.dropFirst(2) } else if s.hasPrefix("H:") { s = s.dropFirst(2) }
        let lead: NSLayoutConstraint.Attribute = vertical ? .top : .leading
        let trail: NSLayoutConstraint.Attribute = vertical ? .bottom : .trailing
        let dim: NSLayoutConstraint.Attribute = vertical ? .height : .width
        var out: [NSLayoutConstraint] = []

        func metric(_ name: Substring) -> CGFloat? {
            if let d = Double(name) { return CGFloat(d) }
            let m = metrics[String(name)]
            if let c = m as? CGFloat { return c }
            if let d = m as? Double { return CGFloat(d) }
            if let i = m as? Int { return CGFloat(i) }
            if let n = m as? NSNumber { return CGFloat(n.doubleValue) }
            return nil
        }
        func predicates(_ text: Substring) -> [Predicate] {
            var body = text
            if body.hasPrefix("(") { body = body.dropFirst().dropLast() }
            return body.split(separator: ",").map { part in
                var p = part
                var rel = NSLayoutConstraint.Relation.equal
                if p.hasPrefix("==") { p = p.dropFirst(2) } else if p.hasPrefix(">=") { rel = .greaterThanOrEqual; p = p.dropFirst(2) } else if p.hasPrefix("<=") { rel = .lessThanOrEqual; p = p.dropFirst(2) }
                var prio: Float?
                if let at = p.firstIndex(of: "@") {
                    prio = metric(p[p.index(after: at)...]).map(Float.init)
                    p = p[..<at]
                }
                if let c = metric(p) { return Predicate(relation: rel, constant: c, view: nil, priority: prio) }
                return Predicate(relation: rel, constant: nil, view: String(p), priority: prio)
            }
        }
        func view(_ name: String) -> NSView? { views[name] as? NSView }

        // Tokenize into: "|", "[...]", and connections "-...-" / "-" / "".
        enum Element { case superview, view(NSView, [Predicate]), connection([Predicate]?) }
        var elements: [Element] = []
        var i = s.startIndex
        var pendingConnection: [Predicate]?? = nil
        func flushConnection() {
            if let pc = pendingConnection { elements.append(.connection(pc)); pendingConnection = nil }
        }
        while i < s.endIndex {
            let c = s[i]
            if c == "|" {
                flushConnection()
                if case .view? = elements.last { elements.append(.connection([Predicate(relation: .equal, constant: 0, view: nil, priority: nil)])) }
                elements.append(.superview)
                i = s.index(after: i)
            } else if c == "[" {
                flushConnection()
                if let last = elements.last, case .view = last { elements.append(.connection([Predicate(relation: .equal, constant: 0, view: nil, priority: nil)])) }
                if case .superview? = elements.last { elements.append(.connection([Predicate(relation: .equal, constant: 0, view: nil, priority: nil)])) }
                guard let close = s[i...].firstIndex(of: "]") else { break }
                let inner = s[s.index(after: i)..<close]
                let nameEnd = inner.firstIndex(of: "(") ?? inner.endIndex
                let name = String(inner[..<nameEnd])
                let preds = nameEnd < inner.endIndex ? predicates(inner[nameEnd...]) : []
                if let v = view(name) {
                    if case .connection? = elements.last {} else if !elements.isEmpty { elements.append(.connection([Predicate(relation: .equal, constant: 0, view: nil, priority: nil)])) }
                    elements.append(.view(v, preds))
                }
                i = s.index(after: close)
            } else if c == "-" {
                // "-" alone (standard), or "-pred-".
                let next = s.index(after: i)
                if next < s.endIndex, s[next] != "[", s[next] != "|" {
                    guard let end = s[next...].firstIndex(of: "-") else { break }
                    pendingConnection = .some(predicates(s[next..<end]))
                    i = s.index(after: end)
                } else {
                    pendingConnection = .some(nil)
                    i = next
                }
                flushConnection()
            } else {
                i = s.index(after: i)
            }
        }

        // Constraints between consecutive elements.
        var prev: Element?
        var connection: [Predicate]?? = nil
        var placed: [NSView] = []
        for e in elements {
            switch e {
            case .connection(let p): connection = .some(p)
            case .superview, .view:
                if let prev {
                    let preds = connection.flatMap { $0 }
                    var a: NSView?, b: NSView?
                    var toSuper = false
                    if case let .view(v, _) = prev { a = v }
                    if case let .view(v, _) = e { b = v }
                    if case .superview = prev { toSuper = true }
                    if case .superview = e { toSuper = true }
                    let gapPreds = preds ?? [Predicate(relation: .equal, constant: toSuper ? superviewSpacing : siblingSpacing, view: nil, priority: nil)]
                    for p in gapPreds {
                        let gap = p.constant ?? (toSuper ? superviewSpacing : siblingSpacing)
                        let c: NSLayoutConstraint
                        if let a, let b {
                            c = NSLayoutConstraint(item: b, attribute: lead, relatedBy: p.relation, toItem: a, attribute: trail, multiplier: 1, constant: gap)
                        } else if let b, let sup = b.superview {
                            c = NSLayoutConstraint(item: b, attribute: lead, relatedBy: p.relation, toItem: sup, attribute: lead, multiplier: 1, constant: gap)
                        } else if let a, let sup = a.superview {
                            let flipped: NSLayoutConstraint.Relation = p.relation == .equal ? .equal : p.relation == .lessThanOrEqual ? .greaterThanOrEqual : .lessThanOrEqual
                            c = NSLayoutConstraint(item: sup, attribute: trail, relatedBy: flipped == .equal ? .equal : flipped, toItem: a, attribute: trail, multiplier: 1, constant: gap)
                        } else { continue }
                        if let pr = p.priority { c.priority = NSLayoutConstraint.Priority(pr) }
                        out.append(c)
                    }
                }
                if case let .view(v, preds) = e {
                    placed.append(v)
                    for p in preds {
                        let c: NSLayoutConstraint
                        if let other = p.view.flatMap(view) {
                            c = NSLayoutConstraint(item: v, attribute: dim, relatedBy: p.relation, toItem: other, attribute: dim, multiplier: 1, constant: 0)
                        } else {
                            c = NSLayoutConstraint(item: v, attribute: dim, relatedBy: p.relation, toItem: nil, attribute: .notAnAttribute, multiplier: 1, constant: p.constant ?? 0)
                        }
                        if let pr = p.priority { c.priority = NSLayoutConstraint.Priority(pr) }
                        out.append(c)
                    }
                }
                prev = e
                connection = nil
            }
        }
        // Alignment options across the placed views.
        let aligns: [(NSLayoutConstraint.FormatOptions, NSLayoutConstraint.Attribute)] = [
            (.alignAllLeft, .left), (.alignAllRight, .right), (.alignAllTop, .top), (.alignAllBottom, .bottom),
            (.alignAllLeading, .leading), (.alignAllTrailing, .trailing), (.alignAllCenterX, .centerX), (.alignAllCenterY, .centerY),
            (.alignAllLastBaseline, .lastBaseline), (.alignAllFirstBaseline, .firstBaseline),
        ]
        for (opt, attr) in aligns where options.contains(opt) && placed.count > 1 {
            for v in placed.dropFirst() {
                out.append(NSLayoutConstraint(item: v, attribute: attr, relatedBy: .equal, toItem: placed[0], attribute: attr, multiplier: 1, constant: 0))
            }
        }
        return out
    }
}

// MARK: Safe areas

/// The views whose safe area something follows (a safe-area layout guide,
/// a scroll view's automatic insets), with the insets last applied.
@MainActor enum SafeArea {
    final class Entry {
        weak var view: NSView?
        var insets = NSEdgeInsets()
        var guide: [NSLayoutConstraint] = []
        init(_ v: NSView) { view = v }
    }
    static var entries: [ObjectIdentifier: Entry] = [:]

    static func track(_ v: NSView, guide: NSLayoutGuide? = nil) {
        let e = entries[ObjectIdentifier(v)] ?? Entry(v)
        entries[ObjectIdentifier(v)] = e
        if let g = guide {
            e.guide = v._constraints.filter { $0.firstItem === g && $0.secondItem === v }
            e.insets = NSEdgeInsets()
            apply(e, v.safeAreaInsets)
        }
    }

    private static func same(_ a: NSEdgeInsets, _ b: NSEdgeInsets) -> Bool {
        a.top == b.top && a.left == b.left && a.bottom == b.bottom && a.right == b.right
    }

    private static func apply(_ e: Entry, _ i: NSEdgeInsets) {
        e.insets = i
        for c in e.guide {
            switch c.firstAttribute {
            case .leading, .left: c.constant = i.left
            case .trailing, .right: c.constant = -i.right
            case .top: c.constant = i.top
            case .bottom: c.constant = -i.bottom
            default: break
            }
        }
    }

    /// Re-reads the tracked views' insets under `root`; whether any changed.
    static func update(under root: NSView) -> Bool {
        guard !entries.isEmpty else { return false }
        var changed = false
        for (id, e) in entries {
            guard let v = e.view else { entries[id] = nil; continue }
            guard v.layoutRoot === root else { continue }
            let i = v.safeAreaInsets
            if !same(i, e.insets) {
                apply(e, i)
                v.safeAreaInsetsDidChange()
                changed = true
            }
        }
        return changed
    }
}
