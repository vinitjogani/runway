// Auto Layout: NSLayoutConstraint, anchors, layout guides, intrinsic
// content size with hugging and compression resistance, autoresizing-mask
// constraints, the visual format language, and the layout pass
// (updateConstraints → solve → layout() top-down), over a Cassowary solver.
//
// Each hierarchy's root view owns a LayoutEngine. Variables are each
// item's left, top, width and height in the root's top-left space; the
// solution becomes frames in each superview's own (flipped or unflipped)
// coordinates. Views with `translatesAutoresizingMaskIntoConstraints` are
// pinned to their frames (which autoresizing moves), as AppKit's
// NSAutoresizingMaskLayoutConstraints do.

import Foundation
import RunwayCore

// MARK: Constraints

@preconcurrency @MainActor
open class NSLayoutConstraint: NSObject {
    public enum Attribute: Int, Sendable {
        case notAnAttribute = 0, left, right, top, bottom, leading, trailing, width, height, centerX, centerY, lastBaseline, firstBaseline
        public static let baseline = Attribute.lastBaseline
    }
    public enum Relation: Int, Sendable { case lessThanOrEqual = -1, equal = 0, greaterThanOrEqual = 1 }
    public enum Orientation: Int, Sendable { case horizontal = 0, vertical = 1 }

    public struct Priority: RawRepresentable, Hashable, Comparable, Sendable, ExpressibleByFloatLiteral, ExpressibleByIntegerLiteral {
        public var rawValue: Float
        public init(rawValue: Float) { self.rawValue = rawValue }
        public init(_ rawValue: Float) { self.rawValue = rawValue }
        public init(floatLiteral value: Float) { rawValue = value }
        public init(integerLiteral value: Int) { rawValue = Float(value) }
        public static let required = Priority(1000)
        public static let defaultHigh = Priority(750)
        public static let dragThatCanResizeWindow = Priority(510)
        public static let windowSizeStayPut = Priority(500)
        public static let dragThatCannotResizeWindow = Priority(490)
        public static let defaultLow = Priority(250)
        public static let fittingSizeCompression = Priority(50)
        public static func < (a: Priority, b: Priority) -> Bool { a.rawValue < b.rawValue }
        public static func + (p: Priority, d: Float) -> Priority { Priority(p.rawValue + d) }
        public static func - (p: Priority, d: Float) -> Priority { Priority(p.rawValue - d) }
        /// The solver weight: nine orders of magnitude from 0 to 999, so
        /// every optional priority stays below required (10^10 for 999
        /// would outweigh it, making 999 constraints required).
        var strength: Double {
            rawValue >= 1000 ? CassowarySolver.required : pow(10, Double(max(0, rawValue)) * 0.009)
        }
    }

    public struct FormatOptions: OptionSet, Sendable {
        public let rawValue: UInt
        public init(rawValue: UInt) { self.rawValue = rawValue }
        public static let alignAllLeft = FormatOptions(rawValue: 1 << 1)
        public static let alignAllRight = FormatOptions(rawValue: 1 << 2)
        public static let alignAllTop = FormatOptions(rawValue: 1 << 3)
        public static let alignAllBottom = FormatOptions(rawValue: 1 << 4)
        public static let alignAllLeading = FormatOptions(rawValue: 1 << 5)
        public static let alignAllTrailing = FormatOptions(rawValue: 1 << 6)
        public static let alignAllCenterX = FormatOptions(rawValue: 1 << 9)
        public static let alignAllCenterY = FormatOptions(rawValue: 1 << 10)
        public static let alignAllLastBaseline = FormatOptions(rawValue: 1 << 11)
        public static let alignAllFirstBaseline = FormatOptions(rawValue: 1 << 12)
        public static let directionLeadingToTrailing = FormatOptions([])
        public static let directionLeftToRight = FormatOptions(rawValue: 1 << 16)
        public static let directionRightToLeft = FormatOptions(rawValue: 2 << 16)
    }

    open private(set) weak var firstItem: AnyObject?
    open private(set) weak var secondItem: AnyObject?
    public let firstAttribute: Attribute
    public let secondAttribute: Attribute
    public let relation: Relation
    public let multiplier: CGFloat
    open var constant: CGFloat { didSet { if constant != oldValue { changed() } } }
    open var priority: Priority = .required { didSet { if priority != oldValue { changed() } } }
    open var identifier: String?
    open var shouldBeArchived = false
    /// Generated by AppKit (autoresizing masks, intrinsic size, guides).
    var isInternal = false

    public init(item view1: Any, attribute attr1: Attribute, relatedBy relation: Relation, toItem view2: Any?, attribute attr2: Attribute,
                multiplier: CGFloat, constant c: CGFloat) {
        firstItem = view1 as AnyObject
        secondItem = view2.map { $0 as AnyObject }
        firstAttribute = attr1
        secondAttribute = view2 == nil ? .notAnAttribute : attr2
        self.relation = relation
        self.multiplier = multiplier
        constant = c
        super.init()
    }
    public convenience init(item view1: Any, attribute attr1: Attribute, relatedBy relation: Relation, toItem view2: Any?, attribute attr2: Attribute,
                            multiplier: CGFloat, constant c: CGFloat, priority: Priority) {
        self.init(item: view1, attribute: attr1, relatedBy: relation, toItem: view2, attribute: attr2, multiplier: multiplier, constant: c)
        self.priority = priority
    }

    open var firstAnchor: AnyObject? { firstItem.map { LayoutItem.of($0)?.anchor(firstAttribute) as AnyObject? } ?? nil }
    open var secondAnchor: AnyObject? { secondItem.map { LayoutItem.of($0)?.anchor(secondAttribute) as AnyObject? } ?? nil }

    /// The view it's installed on.
    weak var owner: NSView?

    open var isActive: Bool {
        get { owner != nil }
        set {
            if newValue {
                guard owner == nil, let v = installationView() else { return }
                v.addConstraint(self)
            } else {
                owner?.removeConstraint(self)
            }
        }
    }

    /// The closest common ancestor of the items' views.
    func installationView() -> NSView? {
        guard let a = firstItem.flatMap(LayoutItem.owningView) else { return nil }
        guard let s = secondItem else { return a }
        guard let b = LayoutItem.owningView(s) else { return nil }
        return a.ancestorShared(with: b)
    }

    public static func activate(_ constraints: [NSLayoutConstraint]) { for c in constraints { c.isActive = true } }
    public static func deactivate(_ constraints: [NSLayoutConstraint]) { for c in constraints { c.isActive = false } }

    func changed() {
        guard let o = owner else { return }
        o.layoutRoot.engine?.constraintChanged(self)
        o.layoutRoot.needsLayout = true
    }

    open override nonisolated var description: String { MainActor.assumeIsolated { describe } }
    private var describe: String {
        func name(_ o: AnyObject?) -> String { o.map { "\(type(of: $0))" } ?? "nil" }
        let rel = relation == .equal ? "==" : relation == .lessThanOrEqual ? "<=" : ">="
        var s = "<NSLayoutConstraint \(name(firstItem)).\(firstAttribute) \(rel)"
        if secondItem != nil { s += " \(multiplier == 1 ? "" : "\(multiplier)*")\(name(secondItem)).\(secondAttribute)" }
        if constant != 0 || secondItem == nil { s += " \(constant >= 0 && secondItem != nil ? "+ " : "")\(constant)" }
        if priority != .required { s += " @\(priority.rawValue)" }
        return s + ">"
    }

    public static func constraints(withVisualFormat format: String, options: FormatOptions = [], metrics: [String: Any]? = nil,
                                   views: [String: Any]) -> [NSLayoutConstraint] {
        VisualFormat.parse(format, options: options, metrics: metrics ?? [:], views: views)
    }
}

