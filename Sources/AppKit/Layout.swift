@preconcurrency @MainActor
open class NSLayoutAnchor<AnchorType: AnyObject>: NSObject {
    let item: LayoutItem
    let attribute: NSLayoutConstraint.Attribute
    init(_ item: LayoutItem, _ a: NSLayoutConstraint.Attribute) { self.item = item; attribute = a; super.init() }
    open var name: String { "\(attribute)" }
    open var item_: AnyObject? { item.target }

    func make(_ r: NSLayoutConstraint.Relation, _ other: NSLayoutAnchor<AnchorType>?, _ m: CGFloat, _ c: CGFloat) -> NSLayoutConstraint {
        NSLayoutConstraint(item: item.target as Any, attribute: attribute, relatedBy: r, toItem: other.map { $0.item.target as Any },
                           attribute: other?.attribute ?? .notAnAttribute, multiplier: m, constant: c)
    }
    open func constraint(equalTo anchor: NSLayoutAnchor<AnchorType>) -> NSLayoutConstraint { make(.equal, anchor, 1, 0) }
    open func constraint(equalTo anchor: NSLayoutAnchor<AnchorType>, constant c: CGFloat) -> NSLayoutConstraint { make(.equal, anchor, 1, c) }
    open func constraint(greaterThanOrEqualTo anchor: NSLayoutAnchor<AnchorType>) -> NSLayoutConstraint { make(.greaterThanOrEqual, anchor, 1, 0) }
    open func constraint(greaterThanOrEqualTo anchor: NSLayoutAnchor<AnchorType>, constant c: CGFloat) -> NSLayoutConstraint { make(.greaterThanOrEqual, anchor, 1, c) }
    open func constraint(lessThanOrEqualTo anchor: NSLayoutAnchor<AnchorType>) -> NSLayoutConstraint { make(.lessThanOrEqual, anchor, 1, 0) }
    open func constraint(lessThanOrEqualTo anchor: NSLayoutAnchor<AnchorType>, constant c: CGFloat) -> NSLayoutConstraint { make(.lessThanOrEqual, anchor, 1, c) }
}

