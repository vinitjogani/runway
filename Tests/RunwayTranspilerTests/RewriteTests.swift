        assertContains(out, "extension AppDelegate { func _runwayPart_AppDelegate<P: RunwayObjC.PartTag>(_ m: inout RunwayObjC.Message, _: P.Type) -> Bool { false } }",
                       "func _runwayPart_AppDelegate(_ m: inout RunwayObjC.Message, _: RunwayObjC.Part0.Type) -> Bool {",
                       #"case "newDoc:": m.result = RunwayObjC.box(self.newDoc(RunwayObjC.arg(a, 0))); return true"#)
