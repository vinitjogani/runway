import SwiftParser
import XCTest
@testable import RunwayTranspiler

/// Before/after cases for the rewrite rules.
final class RewriteTests: XCTestCase {
    static let main = "/pkg/Sources/App/Main.swift"

    /// Transforms `source` as `Main.swift` of a package that also holds `others`.
    func t(_ source: String, others: [(String, String)] = [], file: String = main,
           _ fileLine: StaticString = #filePath, line: UInt = #line) -> String {
        let index = PackageIndex(files: [(file, source)] + others)
        let out = RunwayTranspiler.transform(source: source, fileName: file, index: index)
        let r = RunwayTranspiler.verify(original: source, output: out)
        XCTAssertFalse(r.parseErrors, "output doesn't parse:\n\(out)", file: fileLine, line: line)
        XCTAssertEqual(r.leftovers, [], "left over in:\n\(out)", file: fileLine, line: line)
        XCTAssertFalse(r.linesShifted, "lines moved:\n\(out)", file: fileLine, line: line)
        return out
    }

    /// The part of the output before generated code.
    func body(_ out: String) -> String {
        out.components(separatedBy: "\n// MARK: - Generated by RunwayTranspiler").first!
    }

    func assertContains(_ out: String, _ needles: String..., file: StaticString = #filePath, line: UInt = #line) {
        for n in needles { XCTAssertTrue(out.contains(n), "missing \(n) in:\n\(out)", file: file, line: line) }
    }

    // MARK: Untouched code

    func testCodeWithoutObjCIsUnchanged() {
        let src = """
        import Foundation
        struct Point { var x = 0, y = 0 }
        final class Model {
            var items: [String] = []
            func add(_ s: String) { items.append(s) }
            var dynamicRange: ClosedRange<Int> { 0...1 }   // "dynamic" inside a name
        }
        #if canImport(AppKit)
        let ui = true
        #endif
        """
        XCTAssertEqual(t(src), src)
    }

    func testOtherPlatformConditionsAreLeftAlone() {
        let src = "#if os(Linux)\nlet a = 1\n#elseif os(iOS)\nlet a = 2\n#elseif canImport(UIKit)\nlet a = 3\n#endif\n"
        XCTAssertEqual(t(src), src)
    }

    // MARK: Selectors

    func testSelectorForms() {
        let out = t("""
        import AppKit
        class C: NSObject {
            @objc func a() {}
            @objc func b(_ s: Any?) {}
            @objc func c(_ x: Int, with y: Int) {}
            @objc func d(url: URL) {}
            @objc var e = 0
            func refs() {
                _ = [#selector(a), #selector(b(_:)), #selector(c(_:with:)), #selector(d(url:)), #selector(C.b(_:)),
                     #selector(self.a), #selector(getter: e), #selector(setter: C.e), #selector(b)]
            }
        }
        """)
        assertContains(out, #"Selector("a"), Selector("b:"), Selector("c:with:"), Selector("dWithUrl:"), Selector("b:")"#,
                       #"Selector("a"), Selector("e"), Selector("setE:"), Selector("b:")]"#)
    }

    func testBareSelectorsOutsideThePackage() {
        let out = t("""
        import AppKit
        let a = #selector(NSApplication.terminate)
        let b = #selector(NSWindow.performClose(_:))
        let c = #selector(NSResponder.someUnknownThing)
        """)
        assertContains(out, #"let a = Selector("terminate:")"#, #"let b = Selector("performClose:")"#, #"let c = Selector("someUnknownThing")"#)
    }

    func testBareSelectorResolvesAcrossFiles() {
        let other = ("/pkg/Sources/App/Other.swift", "import AppKit\nclass Target: NSObject { @objc func fire(_ sender: Any?, extra: Int) {} }\n")
        let out = t("import AppKit\nlet s = #selector(Target.fire)\n", others: [other])
        assertContains(out, #"let s = Selector("fire:extra:")"#)
    }

    func testExplicitObjCName() {
        let out = t("import AppKit\nclass C: NSObject {\n    @objc(openFile:) func open(_ f: String) {}\n}\n")
        assertContains(out, #"case "openFile:": m.result = RunwayObjC.box(self.open(RunwayObjC.arg(a, 0))); return true"#)
        XCTAssertTrue(body(out).contains("    func open(_ f: String) {}"))
    }

    func testKeyPathLiteral() {
        let out = t("let a = #keyPath(Doc.title)\nlet b = #keyPath(owner.name)\nlet c = #keyPath(title)\n")
        XCTAssertEqual(out, "let a = \"title\"\nlet b = \"owner.name\"\nlet c = \"title\"\n")
    }

    // MARK: Attributes

    func testAttributesAreStripped() {
        let out = t("""
        import AppKit
        @objc(MYThing) @objcMembers
        final class Thing: NSObject {
            @IBOutlet weak var view: NSView!
            @IBOutlet private var views: [NSView]!
            @IBInspectable var radius: Double = 2
            @IBAction private func go(_ sender: Any) {}
            @nonobjc func swiftOnly() {}
        }
        @objc enum Kind: Int { case a, b }
        """)
        let b = body(out)
        XCTAssertTrue(b.contains("\nfinal class Thing: NSObject, @preconcurrency RunwayObjC.SelectorDispatching {"))
        XCTAssertTrue(b.contains("    weak var view: NSView!\n"))
        XCTAssertTrue(b.contains("    private var views: [NSView]!\n"))
        XCTAssertTrue(b.contains("    private func go(_ sender: Any) {}\n"))
        XCTAssertTrue(b.contains("    func swiftOnly() {}\n"))
        XCTAssertTrue(b.contains("enum Kind: Int { case a, b }"))
        // @nonobjc members stay out of the table; @objcMembers brings the rest in.
        XCTAssertFalse(out.contains("\"swiftOnly\""))
        assertContains(out, #"case "go:""#, #"case "radius""#, #"case "setRadius:""#)
    }

    // MARK: Platform conditions

    func testMacConditionsTakeTheMacBranch() {
        let src = """
        #if os(macOS)
        let a = 1
        #elseif os( OSX )
        let a = 2
        #endif
        #if !os(macOS) && targetEnvironment(macCatalyst)
        let b = 1
        #endif
        #if os(iOS) || os(macOS)
        let c = 1
        #endif
        """
        XCTAssertEqual(t(src), """
        #if true
        let a = 1
        #elseif true
        let a = 2
        #endif
        #if !true && false
        let b = 1
        #endif
        #if os(iOS) || true
        let c = 1
        #endif
        """)
    }

    func testIOSPreviewSelectsMobileBranchesAndOptsIntoSimulatorCode() {
        let source = """
        #if os(macOS) || os(OSX)
        let platform = "Mac"
        #elseif DEBUG && (os(iOS) || targetEnvironment(simulator))
        let platform = "iPhone"
        #elseif os(Linux) && !targetEnvironment(macCatalyst)
        let platform = "Linux"
        #endif
        let literal = "os(iOS)"
        """
        let expected = """
        #if false || false
        let platform = "Mac"
        #elseif DEBUG && (true || targetEnvironment(simulator))
        let platform = "iPhone"
        #elseif os(Linux) && !targetEnvironment(macCatalyst)
        let platform = "Linux"
        #endif
        let literal = "os(iOS)"
        """
        XCTAssertEqual(IOSPreview().rewriteConditions(in: source), expected)
        XCTAssertEqual(IOSPreview(includingSimulatorCode: true).rewriteConditions(in: source),
                       expected.replacingOccurrences(of: "true || targetEnvironment(simulator)", with: "true || true"))
    }

    func testIOSPreviewPreservesMultilineCompoundConditions() {
        let source = """
        #if os(
            iOS
        ) || os(macOS)
        let platform = "iPhone"
        #endif
        """
        let expected = """
        #if (true

        ) || false
        let platform = "iPhone"
        #endif
        """
        for ending in ["\n", "\r\n"] {
            XCTAssertEqual(IOSPreview().rewriteConditions(in: source.replacingOccurrences(of: "\n", with: ending)),
                           expected.replacingOccurrences(of: "\n", with: ending))
        }
    }

    // MARK: KVO

    func testDynamicPropertyGetsObservers() {
        let out = t("""
        import Foundation
        class M: NSObject {
            @objc dynamic var title = ""
            @objc dynamic var count: Int = 0 {
                didSet { print(count) }
            }
            @objc dynamic var mode = 0 { willSet(next) { print(next) } didSet(previous) { print(previous) } }
            @objc dynamic var computed: Int { count * 2 }
            @objc dynamic let fixed = 1
        }
        """)
        let b = body(out)
        assertContains(b,
            #"    var title = "" { willSet { RunwayObjC.KVO.willChange(self, "title") } didSet { RunwayObjC.KVO.didChange(self, "title", old: oldValue, new: self.title) } }"#,
            #"        didSet { RunwayObjC.KVO.didChange(self, "count", old: oldValue, new: self.count); print(count) }"#,
            #"    willSet { RunwayObjC.KVO.willChange(self, "count") } }"#,
            #"willSet(next) { RunwayObjC.KVO.willChange(self, "mode"); print(next) } didSet(previous) { RunwayObjC.KVO.didChange(self, "mode", old: previous, new: self.mode); print(previous) } }"#,
            "    var computed: Int { count * 2 }\n", "    let fixed = 1\n")
        // KVC knows them; only the stored, observed ones notify by themselves.
        assertContains(out, #"case "title": self.title = RunwayObjC.arg([v], 0); m.notifies = true; return true"#,
                       #"case "computed": m.result = RunwayObjC.box(self.computed); return true"#)
        XCTAssertFalse(out.contains("self.computed = "))
        XCTAssertFalse(out.contains("self.fixed = "))
    }

    func testObserveGetsTheKeyName() {
        let out = t("""
        import Foundation
        func f(_ m: Model) {
            let a = m.observe(\\.title, options: [.new]) { _, _ in }
            let b = m.observe(\\Model.owner?.name) { _, _ in }
            let c = m.observe(\\.items[0], options: []) { _, _ in }
            let d = publisher.observe(\\.title)
        }
        """)
        assertContains(out, #"m.observe(\.title, _runwayKey: "title", options: [.new])"#,
                       #"m.observe(\Model.owner?.name, _runwayKey: "owner.name") { _, _ in }"#,
                       #"m.observe(\.items[0], options: [])"#, #"publisher.observe(\.title)"#)
    }

    func testObserveValueOverrideOnNSObjectRoot() {
        let out = t("""
        import Foundation
        class Watcher: NSObject {
            override func observeValue(forKeyPath keyPath: String?, of object: Any?, change: [NSKeyValueChangeKey: Any]?, context: UnsafeMutableRawPointer?) {
                super.observeValue(forKeyPath: keyPath, of: object, change: change, context: context)
            }
        }
        class SubWatcher: Watcher {
            override func observeValue(forKeyPath keyPath: String?, of object: Any?, change: [NSKeyValueChangeKey: Any]?, context: UnsafeMutableRawPointer?) {
                super.observeValue(forKeyPath: keyPath, of: object, change: change, context: context)
            }
        }
        """)
        let lines = body(out).components(separatedBy: "\n")
        XCTAssertEqual(lines[1], "class Watcher: NSObject, @preconcurrency RunwayObjC.KeyValueObserving {")
        XCTAssertTrue(lines[2].hasPrefix("    func observeValue("))
        XCTAssertEqual(lines[3], "        RunwayObjC.KVO.unhandledObservation(forKeyPath: keyPath, of: object, change: change, context: context)")
        XCTAssertEqual(lines[6], "class SubWatcher: Watcher {")
        XCTAssertTrue(lines[7].hasPrefix("    override func observeValue("))
        XCTAssertTrue(lines[8].contains("super.observeValue("))
    }

