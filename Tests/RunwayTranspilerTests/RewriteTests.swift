    func testLineNumbersOfEveryOriginalLineHold() throws {
        let src = """
        import AppKit
        @objcMembers
        class A: NSObject {
            @objc dynamic var x = 0
            @IBOutlet
            weak var v: NSView?
            @IBAction
            func go(_ s: Any?) { perform(#selector(go(_:)), with: nil, afterDelay: 1) }
        }
        let marker = 1
        """
        let out = t(src)
        let lines = out.components(separatedBy: "\n")
        XCTAssertEqual(lines[9], "let marker = 1")
        XCTAssertEqual(lines[7], #"    func go(_ s: Any?) { perform(Selector("go:"), with: nil, afterDelay: 1) }"#)
    }
