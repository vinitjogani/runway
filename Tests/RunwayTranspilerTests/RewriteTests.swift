    func testSubclassInAnotherFileOverridesTheHook() {
        let base = ("/pkg/Sources/App/Base.swift", "import AppKit\nclass BaseVC: NSViewController { @objc func a() {} }\n")
        let out = t("import AppKit\nclass Sub: BaseVC { @objc func b() {} }\nclass Plain: BaseVC { func c() {} }\n", others: [base])
        assertContains(body(out), "class Sub: BaseVC { func b() {} ; override func _runwayHandle(_ m: inout RunwayObjC.Message) -> Bool { if _runwayPart_Sub(&m, RunwayObjC.Part0.self) { return true }; return super._runwayHandle(&m) } }",
                       "class Plain: BaseVC { func c() {} }")
    }

    func testExtensionsInOtherFilesAddParts() {
        let ext = ("/pkg/Sources/App/AppDelegate+Menu.swift", "import AppKit\nextension AppDelegate {\n    @objc private func showHelp(_ s: Any?) {}\n}\n")
        let main = "import AppKit\nclass AppDelegate: NSObject {\n    @objc func a() {}\n}\n"
        let out = t(main, others: [ext])
        assertContains(out, "if _runwayPart_AppDelegate(&m, RunwayObjC.Part0.self) { return true }; if _runwayPart_AppDelegate(&m, RunwayObjC.Part1.self) { return true }; return false")
        // Parts go by path: the extension's file is part 0, where its private method is visible.
        let index = PackageIndex(files: [(Self.main, main), ext])
        let extOut = RunwayTranspiler.transform(source: ext.1, fileName: ext.0, index: index)
        assertContains(extOut, "    private func showHelp(_ s: Any?) {}", "func _runwayPart_AppDelegate(_ m: inout RunwayObjC.Message, _: RunwayObjC.Part0.Type) -> Bool {",
                       #"case "showHelp:""#)
        assertContains(out, "func _runwayPart_AppDelegate(_ m: inout RunwayObjC.Message, _: RunwayObjC.Part1.Type) -> Bool {", #"case "a": m.result"#)
        XCTAssertFalse(extOut.contains("SelectorDispatching"))
    }

