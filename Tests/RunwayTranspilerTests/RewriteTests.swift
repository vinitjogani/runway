    func testOptionalRequirementCalls() {
        let proto = ("/pkg/Sources/App/Proto.swift", "import AppKit\n@objc protocol D { @objc optional func didFinish(_ x: Int); @objc optional func should() -> Bool; @objc optional func pair(_ a: Int, with b: Int) }\n")
        let out = t("""
        import AppKit
        final class Worker {
            weak var delegate: D?
            var other: D!
            var onDone: ((Int) -> Void)?
            func run() {
                delegate?.didFinish?(1)
                let ok = delegate?.should?() ?? true
                other.pair?(1, with: 2)
                self.delegate?.didFinish?(2)
                onDone?(3)
            }
        }
        """, others: [proto])
        assertContains(out,
            #"RunwayObjC.ifResponds(delegate, Selector("didFinish:"))?.didFinish(1)"#,
            #"let ok = RunwayObjC.ifResponds(delegate, Selector("should"))?.should() ?? true"#,
            #"RunwayObjC.ifResponds(other, Selector("pair:with:"))?.pair(1, with: 2)"#,
            #"RunwayObjC.ifResponds(self.delegate, Selector("didFinish:"))?.didFinish(2)"#,
            "onDone?(3)")
    }

