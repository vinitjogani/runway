import XCTest
@testable import RunwayTranspiler

/// Apple macros with no implementation off Apple's toolchain, rewritten at staging.
final class AppleMacroTests: XCTestCase {
    func t(_ source: String, _ fileLine: StaticString = #filePath, line: UInt = #line) -> String {
        let file = "/pkg/Sources/App/Main.swift"
        let out = RunwayTranspiler.transform(source: source, fileName: file, index: PackageIndex(files: [(file, source)]))
        let r = RunwayTranspiler.verify(original: source, output: out)
        XCTAssertFalse(r.parseErrors, "output doesn't parse:\n\(out)", file: fileLine, line: line)
        XCTAssertFalse(r.linesShifted, "lines moved:\n\(out)", file: fileLine, line: line)
        return out
    }
    func body(_ out: String) -> String { out.components(separatedBy: "\n// MARK: - Generated by RunwayTranspiler").first! }
    func assertContains(_ out: String, _ needles: String..., file: StaticString = #filePath, line: UInt = #line) {
        for n in needles { XCTAssertTrue(out.contains(n), "missing \(n) in:\n\(out)", file: file, line: line) }
    }

    func testPreviewMacroIsBlankedKeepingLines() {
        let out = t("""
        import SwiftUI
        struct V: View { var body: some View { Text("x") } }
        #Preview {
            V()
        }
        let after = 1
        """)
        XCTAssertFalse(out.contains("#Preview"))
        XCTAssertTrue(out.contains("\n\n\n\nlet after = 1") || out.contains("let after = 1"))
        XCTAssertEqual(out.components(separatedBy: "\n").count, 6)
    }

    func testDelegateAdaptorGetsAFactory() {
        let out = t("""
        import SwiftUI
        @main struct A: App {
            @NSApplicationDelegateAdaptor(AppDelegate.self) private var appDelegate
            @NSApplicationDelegateAdaptor var other: OtherDelegate
            @UIApplicationDelegateAdaptor(MobileDelegate.self) private var mobileDelegate
            @SwiftUI.UIApplicationDelegateAdaptor var otherMobile: OtherMobileDelegate
            var body: some Scene { WindowGroup { Text("x") } }
        }
        """)
        assertContains(out, "@NSApplicationDelegateAdaptor(AppDelegate.self, { AppDelegate() }) private var appDelegate",
                       "@NSApplicationDelegateAdaptor(OtherDelegate.self, { OtherDelegate() }) var other",
                       "@UIApplicationDelegateAdaptor(MobileDelegate.self, { MobileDelegate() }) private var mobileDelegate",
                       "@SwiftUI.UIApplicationDelegateAdaptor(OtherMobileDelegate.self, { OtherMobileDelegate() }) var otherMobile")
    }

    func testModelBecomesObservablePersistentModel() {
        let out = t("""
        import SwiftData
        @Model
        class Item {
            var title = ""
            @Relationship(deleteRule: .cascade, inverse: \\Content.item)
            var contents: [Content] = []
            @Transient private var cache: Int?
            init() {}
        }
        @Model
        class Content {
            @Attribute(.unique) var type: String = ""
            @Relationship
            var item: Item?
            init() {}
        }
        """)
        assertContains(body(out), "@Observable nonisolated\nclass Item", "@ObservationIgnored private var cache")
        XCTAssertFalse(body(out).contains("@Relationship"))
        XCTAssertFalse(body(out).contains("@Attribute"))
        assertContains(out, "extension Item: SwiftData.PersistentModel",
                       ".toMany(\\Item.contents, inverse: \\Content.item, cascade: true)",
                       ".toOne(\\Content.item, cascade: false)")
    }

    func testSubmoduleImportsNameTheFramework() {
        let out = t("""
        import os.log
        import Carbon.HIToolbox
        import AppKit.NSEvent
        import struct Foundation.URL
        import ObjectiveC
        """)
        assertContains(out, "import os\n", "import Carbon\n", "import AppKit\n", "import struct Foundation.URL", "import Foundation")
        XCTAssertFalse(out.contains("ObjectiveC"))
    }
}
